      IF (ISET.EQ.0) THEN
         DO 5 J=1,12
         DO 5 I=1,12
         IF (AKIV(I,J).GT.0.) AKIV(I,J)=LOG10(AKIV(I,J))
         IF (AKIV(I,J).LE.-0.9D0 .AND. AKIV(I,J).GE.-1.1D0)
     1      AKIV(I,J)=-99.D0
    5    CONTINUE
         ISET=1
      END IF
      J=1
      DO 10 JJ=2,11
      IF (TL.GE.TGK(JJ)) J=JJ
   10 CONTINUE
      DO 30 M=1,4
      JR=J+M-2
      IOK(M)=0
      VR(M)=0.
      IF (JR.LT.1 .OR. JR.GT.12) GO TO 30
      ND=0
      DO 20 K=1,12
