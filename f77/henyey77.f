C     ******************************************************************
C     *                                                                *
C     *    A PROGRAM FOR THE AUTOMATIC COMPUTATION OF STELLAR          *
C     *    EVOLUTION BY THE METHOD OF                                  *
C     *                                                                *
C     *    L. G. HENYEY, J. E. FORBES, AND N. L. GOULD,                *
C     *    ASTROPHYSICAL JOURNAL 139, 306 (1964)  (METHOD II)          *
C     *                                                                *
C     *    THE STAR IS DIVIDED INTO ZONES BY MESH POINTS OF THE        *
C     *    LAGRANGIAN VARIABLE XI, 0 .LE. XI .LE. 1, WITH ALL          *
C     *    QUANTITIES EVALUATED AT THE SAME MESH POINTS.  THE          *
C     *    ARTIFICIAL VARIABLES OF THE PAPER ARE USED THROUGHOUT,      *
C     *         P = (PRESSURE)**(1/4)      (EQ. 8)                     *
C     *         Q = (DENSITY)**(1/3)       (EQ. 9)                     *
C     *         L = XI**2 * F              (EQ. 10, PSEUDOFLUX)        *
C     *         K = 3*KAPPA*P**3/(256*PI*G*SIGMA*T**3)   (EQ. 11)      *
C     *    THE DIFFERENCE EQUATIONS ARE EQS. (22)-(26) OF THE PAPER    *
C     *    WITH BACKWARD TIME DIFFERENCES.  THE LINEARIZED SYSTEM      *
C     *    IS SOLVED BY THE ELIMINATION SCHEME OF EQS. (39)-(46),      *
C     *    WITH THE VECTORS  U = (R,F)  AND  V = (T,Q)  AND THE        *
C     *    RECURSION  DELTA-U(J) + ALPHA(J)*DELTA-V(J) + GAMMA(J) = 0. *
C     *                                                                *
C     *    THE INTERIOR MESH COVERS THE MASS (1-DELS)*M.  THE OUTER    *
C     *    FRACTION DELS = 1.E-5 IS TREATED BY A SEPARATE ENVELOPE     *
C     *    INTEGRATION (SUBROUTINE ENVEL), WHICH SUPPLIES THE FITTED   *
C     *    BOUNDARY QUANTITIES OF EQS. (30)-(33) AS FUNCTIONS OF THE   *
C     *    TOTAL RADIUS AND LUMINOSITY, IN THE MANNER OF THE VARDYA    *
C     *    OUTER-ZONE PROGRAM REFERRED TO IN THE PAPER.  THE OUTER     *
C     *    LAYERS FOLLOW THE BLANKETED RADIATIVE T-TAU RELATION OF     *
C     *    HENYEY, VARDYA + BODENHEIMER (1965), WITH SAHA IONIZATION   *
C     *    AND BOEHM-VITENSE MIXING-LENGTH CONVECTION BELOW.           *
C     *                                                                *
C     *    THE MATERIAL FUNCTIONS FOLLOW THE BERKELEY PRODUCTION       *
C     *    CODE AS PUBLISHED IN BODENHEIMER, FORBES, GOULD + HENYEY    *
C     *    (1965) - APPENDIX A EQUATION OF STATE WITH ELECTRON         *
C     *    DEGENERACY, APPENDIX B KELLER-MEYEROTT OPACITY WITH         *
C     *    MESTEL CONDUCTION AND AN H-MINUS TERM AT LOW T - WITH THE   *
C     *    FULL NUCLEAR NETWORK OF THEIR APPENDIX C - THE PP CHAIN     *
C     *    WITH EXPLICIT HE3 AND THE BE7 ENERGY BRANCHING, AND THE     *
C     *    CNO BI-CYCLE WITH EXPLICIT C12, C13, N14, O16 - IN THE      *
C     *    APPENDIX C IMPLICIT SCHEME (CF88 RATES, GRABOSKE ET AL.     *
C     *    1973 SCREENING).                                            *
C     *                                                                *
C     *    INPUT IS READ FROM UNIT 5 (CARD READER).                    *
C     *    OUTPUT IS WRITTEN ON UNIT 6 (LINE PRINTER).                 *
C     *    FORTRAN IV.  SINGLE PRECISION THROUGHOUT.                   *
C     *                                                                *
C     *    CARD 1 (3F10.5)   TOTM   = STELLAR MASS, SOLAR UNITS        *
C     *                      XHYD0  = INITIAL HYDROGEN FRACTION X      *
C     *                      ZMET   = HEAVY ELEMENT FRACTION Z         *
C     *    CARD 2 (2I5,E10.3,F10.5,E10.3,I5)                           *
C     *                      N      = NUMBER OF MESH POINTS (.LE.201)  *
C     *                      NMODS  = NUMBER OF MODELS IN SEQUENCE     *
C     *                      DTYR   = INITIAL TIME STEP, YEARS         *
C     *                      CLIM   = CORRECTION LIMITER (0.1 - 0.3)   *
C     *                      EPSC   = CONVERGENCE TOLERANCE            *
C     *                      NPRIN  = STRUCTURE PRINT INTERVAL         *
C     *                                                                *
C     ******************************************************************
C
C     ------------------------------------------------------------------
C     MAIN PROGRAM - CONTROLS THE EVOLUTIONARY SEQUENCE (FIG. 2 OF
C     THE PAPER).  REACTION-COMPOSITION STEP, HENYEY ITERATIONS,
C     TIME STEP CONTROL.
C     ------------------------------------------------------------------
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /GRID/ XI(201),EMPT(201),EMH(201),EMPH(201),N
      COMMON /VARBL/ R(201),F(201),T(201),Q(201),XH(201),X3A(201)
      COMMON /OLDT/ QN(201),EN(201),DTINV
      COMMON /THERM/ PP(201),DPT(201),DPQ(201),EE(201),DET(201),
     1   DEQ(201),CK(201),DKT(201),DKQ(201),CPA(201),EP(201),
     2   DEPT(201),DEPQ(201)
      COMMON /FLAGS/ ICV(201)
      COMMON /CONST/ G,SIG,ARAD,RGAS,PI,C256,C4PS,C8PI
      COMMON /STARP/ XM,XMI,ZMET,QHYD
      COMMON /CTRL/ CLIM,EPSC,ITMAX,ALFA
      COMMON /SURF/ RSTAR,XLSTA,DXR,DXL
      COMMON /BRNC/ DX3MX
      COMMON /CNOC/ X12A(201),X13A(201),X14A(201),X16A(201)
      COMMON /CNOZ/ X120,X130,X140,X160
      COMMON /EOSC/ IEOS,IOPC
      COMMON /STRTC/ IHAY
      DIMENSION RSV(201),FSV(201),TSV(201),QSV(201),XSV(201),ESV(201)
      DIMENSION X3SV(201)
      DIMENSION X12SV(201),X13SV(201),X14SV(201),X16SV(201)
C
C     PHYSICAL CONSTANTS (C.G.S.)
      G=6.668D-8
      SIG=5.67D-5
      ARAD=7.565D-15
      RGAS=8.25D7
      PI=3.1415927
      C256=256.*PI*G*SIG
      C4PS=4.*PI*SIG
      C8PI=8./PI
      SECYR=3.156D7
C     ENERGY RELEASE PER GRAM OF HYDROGEN CONSUMED
      QHYD=6.3D18
C
C     READ THE CONTROL CARDS (UNIT 5 = CARD READER)
      READ (5,500) TOTM,XHYD0,ZMET,X3IN
      READ (5,501) N,NMODS,DTYR,CLIM,EPSC,NPRIN,ALFA,IEOS,IOPC,
     1   IHAY
      IF (ALFA.LE.0.) ALFA=1.5
C     EQUATION OF STATE SELECTION (CARD 2, FIELD 8) - BLANK OR 0
C     GIVES THE SAUMON, CHABRIER + VAN HORN (1995) TABLES WITH THE
C     BFGH APPENDIX A FORM ABOVE THE TABLE CEILING; 1 GIVES THE
C     BFGH FORM THROUGHOUT (THE PRE-PHASE-3 PHYSICS).
      IF (IEOS.NE.1) IEOS=0
      IF (IEOS.EQ.0) CALL SCVRD
C     OPACITY SELECTION (CARD 2, FIELD 9) - BLANK OR 0 ADDS THE
C     ALEXANDER, JOHNSON + RYPMA (1983) MOLECULE-AND-GRAIN TABLE
C     BELOW 1.E4 K WITH THE LBA97 EQ. (2.1) HELIUM SCALING;
C     1 KEEPS THE BFGH + H-MINUS STACK THROUGHOUT.
      IF (IOPC.NE.1) IOPC=0
C     START MODE (CARD 2, FIELD 10) - BLANK OR 0 BEGINS NEAR THE
C     MAIN SEQUENCE; 1 BEGINS HIGH ON THE HAYASHI TRACK (LB93
C     CONVENTIONS - LOG L > -1, RHO(C) < 0.1) WITH THE INITIAL
C     STATIC MODEL CLOSED BY A UNIFORM ARTIFICIAL ENERGY
C     GENERATION L/M, AND THE SEQUENCE THEN CONTRACTS ONTO THE
C     MAIN SEQUENCE UNDER THE TIME-DEPENDENT TERMS.
      IF (IHAY.NE.1) IHAY=0
      XM=TOTM*1.989D33
C     THE INTERIOR MESH COVERS THE MASS XMI = (1-DELS)*M.  THE
C     OUTER FRACTION DELS IS CARRIED BY THE SEPARATE ENVELOPE
C     INTEGRATION (SUBROUTINE ENVEL), IN THE MANNER OF THE
C     OUTER-ZONE PROGRAM OF THE PAPER (EQS. 30-33).
C     THE FRACTION IS KEPT SMALL - AT THE TIP OF THE GIANT
C     BRANCH THE ENVELOPE SOLUTION IS THE CLASSICALLY
C     MULTIVALUED ONE, AND WHATEVER PART OF IT LIVES INSIDE THE
C     STATIC INTEGRATION CARRIES NO TIME TERMS AND OFFERS THE
C     SURFACE NEWTON A FOLD THAT NO TIME STEP CAN RESOLVE.  WITH
C     DELS = 1.E-5 THE HYDROGEN-IONIZATION REGION OF A TIP GIANT
C     RIDES THE TIME-DEPENDENT MESH EVEN AT A THOUSAND SOLAR
C     LUMINOSITIES, WHERE THE DISTENDED ATMOSPHERE HAS CLIMBED
C     TO AN EXTERIOR MASS FRACTION NEAR 3.E-5 (AT DELS = 1.E-4
C     THE BRIGHTEST TIPS PUSHED THEIR IONIZATION ZONES BACK
C     OUTSIDE THE MESH AND THE FOLD RETURNED).  THE LOW-PRESSURE
C     ZONES THIS CREATES ARE SERVED BY THE SAHA BRANCH OF
C     STATEB, WHILE THE SUPERADIABATIC LAYER OF A DWARF, AT A
C     MASS FRACTION NEAR 1.E-7, STAYS WITH THE MIXING-LENGTH
C     ENVELOPE AND THE SOLAR CALIBRATION KEEPS ITS MEANING.
      DELS=1.0D-5
      XMI=XM*(1.-DELS)
      WRITE (6,510)
      WRITE (6,511)
      WRITE (6,512)
      WRITE (6,513) XM,XHYD0,ZMET
      WRITE (6,514) N,NMODS,DTYR
      WRITE (6,516) X3IN
      WRITE (6,517) ALFA
      IF (IEOS.EQ.0) WRITE (6,518)
      IF (IEOS.EQ.1) WRITE (6,519)
      IF (IOPC.EQ.0) WRITE (6,522)
      IF (IOPC.EQ.1) WRITE (6,523)
      IF (IHAY.EQ.1) WRITE (6,524)
C
C     SET UP THE FIXED MASS MESH.  THE MASS DISTRIBUTION M(XI) IS
C     NEVER VARIED (SEC. V OF THE PAPER).  WE ADOPT
C         M(XI) = M * XI**3 * (10 - 15*XI + 6*XI**2)
C     WHICH CONCENTRATES THE ZONING AT BOTH CENTER AND SURFACE.
      NM1=N-1
      DO 10 J=1,N
      XX=DBLE(J-1)/DBLE(NM1)
      XI(J)=XX
      EMPT(J)=XMI*XX**3*(10.-15.*XX+6.*XX*XX)
   10 CONTINUE
      DO 20 J=1,NM1
      XX=0.5*(XI(J)+XI(J+1))
      EMH(J)=XMI*XX**3*(10.-15.*XX+6.*XX*XX)
      EMPH(J)=30.*XMI*XX*XX*(1.-XX)**2
   20 CONTINUE
C
C     UNIFORM INITIAL COMPOSITION.  X3IN .GE. 0 GIVES A UNIFORM
C     INITIAL HE3 MASS FRACTION (LBA97 TAKE ZERO).  X3IN .LT. 0
C     SETS HE3 TO ITS LOCAL EQUILIBRIUM VALUE IN THE FIRST
C     APPROXIMATION, FOR COMPARISON WITH THE EQUILIBRIUM-CHAIN
C     PROGRAM IN THE REPOSITORY ROOT.
      X3G=MAX(X3IN,0.D0)
C     INITIAL CNO ABUNDANCES AS FIXED FRACTIONS OF Z (SOLAR
C     DISTRIBUTION - C12 0.172, C13 0.002, N14 0.053, O16 0.482;
C     THE REMAINING 0.291 OF Z, THE NE-FE GROUP, IS INERT).  THE
C     NETWORK OF BFGH (1965) APPENDIX C FOLLOWS ALL FOUR SPECIES
C     OUT OF EQUILIBRIUM.
      X120=0.172*ZMET
      X130=0.002*ZMET
      X140=0.053*ZMET
      X160=0.482*ZMET
      DO 30 J=1,N
      XH(J)=XHYD0
      X3A(J)=X3G
      X12A(J)=X120
      X13A(J)=X130
      X14A(J)=X140
      X16A(J)=X160
      QN(J)=0.
      EN(J)=0.
   30 CONTINUE
C
C     FIRST APPROXIMATION FROM THE EMDEN POLYTROPE N=3
      CALL START(TOTM,XHYD0,X3G,0)
      CALL PHYSIC
      CALL CONVCK(0)
      IF (X3IN.GE.0.) GO TO 35
      DO 32 J=1,N
      CALL RATES(T(J),Q(J),XHYD0,0.D0,ZMET,C1Z,C3Z,C4Z,
     1   RD1,RD2,RD3,RD4,FBZ)
      RPZ=C1Z*XHYD0*XHYD0
      X3E=0.
      IF (C3Z.GT.1.D-30) X3E=(-C4Z+SQRT(C4Z*C4Z+8.*C3Z*RPZ))
     1   /(4.*C3Z)
      X3A(J)=MIN(X3E,1.D-2)
   32 CONTINUE
   35 CONTINUE
C
C     ------------------------------------------------------------------
C     INITIAL (STATIC) MODEL.  THE TIME DERIVATIVE TERMS ARE
C     SUPPRESSED BY SETTING 1/(DELTA T) = 0.
C     ------------------------------------------------------------------
      DTINV=0.
      ITMAX=60
      MODNO=1
      WRITE (6,515) MODNO
      CALL SOLVE(NIT,IER)
      IF (IER.EQ.0) GO TO 40
C     NO CONVERGENCE FROM THE EPSILON-SHAPED PSEUDOFLUX GUESS -
C     REBUILD THE FIRST APPROXIMATION WITH THE AMPLITUDE
C     NORMALIZED TO THE LUMINOSITY GUESS (SEE START) AND TRY
C     ONCE MORE
      WRITE (6,542)
      CALL START(TOTM,XHYD0,X3G,1)
      CALL SOLVE(NIT,IER)
      IF (IER.EQ.0) GO TO 40
      WRITE (6,540)
      STOP 1
   40 CONTINUE
C     THE ARTIFICIAL CONTRACTION LUMINOSITY SERVED ONLY THE
C     INITIAL STATIC MODEL - FROM HERE THE TIME-DEPENDENT TERMS
C     CARRY THE GRAVITATIONAL ENERGY RELEASE
      IHAY=0
      ITMAX=30
      AGEYR=0.
      DT=DTYR*SECYR
      DTY2=DTYR
      WRITE (6,520)
      XLSOL=XLSTA/3.86D33
      RSOL=RSTAR/6.96D10
      TEFF=SQRT(SQRT(XLSTA/(C4PS*RSTAR*RSTAR)))
      RHOC=Q(1)**3
      PC=PP(1)**4
      WRITE (6,521) MODNO,AGEYR,DTY2,NIT,XLSOL,RSOL,TEFF,T(1),RHOC,
     1   PC,XH(1)
      CALL PRINTM
C
C     ------------------------------------------------------------------
C     EVOLUTIONARY SEQUENCE
C     ------------------------------------------------------------------
      IF (NMODS.LE.1) STOP
      DO 300 NMOD=2,NMODS
C     SAVE THE CONVERGED MODEL FOR THE OLD EPOCH AND FOR RETRIES
      DO 210 J=1,N
      QN(J)=Q(J)
      EN(J)=EE(J)
      RSV(J)=R(J)
      FSV(J)=F(J)
      TSV(J)=T(J)
      QSV(J)=Q(J)
      XSV(J)=XH(J)
      X3SV(J)=X3A(J)
      X12SV(J)=X12A(J)
      X13SV(J)=X13A(J)
      X14SV(J)=X14A(J)
      X16SV(J)=X16A(J)
      ESV(J)=EP(J)
  210 CONTINUE
      RSSV=RSTAR
      XLSV=XLSTA
      NTRY=0
C     COMPOSITION STEP - THE NUCLEAR NETWORK ADVANCES X(H1) AND
C     X(HE3) BY THE CONVERGED RATES (HE3 BY AN UNCONDITIONALLY
C     STABLE BACKWARD-EULER STEP), AND CONVECTIVE REGIONS ARE
C     THEN MIXED (FIRST BOX OF FIG. 2).  ON A RETRY THE
C     COMPOSITION IS FIRST RESTORED.
  220 DO 230 J=1,N
      XH(J)=XSV(J)
      X3A(J)=X3SV(J)
      X12A(J)=X12SV(J)
      X13A(J)=X13SV(J)
      X14A(J)=X14SV(J)
      X16A(J)=X16SV(J)
  230 CONTINUE
      CALL BURN(DT)
      CALL MIX
C     THE HE3 STEP MEASURE COMPARES THE MIXED COMPOSITION WITH
C     THE OLD ONE, SO THAT LOCAL PRODUCTION WHICH CONVECTION
C     IMMEDIATELY DILUTES OVER THE CONVECTIVE REGION CANNOT
C     THROTTLE THE TIME STEP.  ONLY ENERGETICALLY SIGNIFICANT
C     POINTS ARE CONSULTED.
      DX3MX=0.
C     THE SIGNIFICANCE GATE MEASURES AGAINST THE PEAK GENERATION
C     RATE WHEREVER IT SITS - AGAINST THE CENTER ALONE, A SHELL
C     STAR (CENTRAL EPSILON ZERO) WOULD PASS EVERY ZONE, AND THE
C     SLOW HE3 RELAXATION AT THE COOL EDGE OF THE SHELL WOULD
C     THROTTLE THE GIANT-BRANCH CLOCK FOR NOTHING.
      EPC=1.D-30
      DO 234 J=1,N
      IF (EP(J).GT.EPC) EPC=EP(J)
  234 CONTINUE
      DO 235 J=1,N
      DXR=ABS(X3A(J)-X3SV(J))/(X3A(J)+1.D-3)
      IF (EP(J).GT.1.D-4*EPC .AND. DXR.GT.DX3MX) DX3MX=DXR
  235 CONTINUE
      DTINV=1./DT
      CALL SOLVE(NIT,IER)
      IF (IER.EQ.0) GO TO 260
C     NO CONVERGENCE - RESTORE THE MODEL, HALVE THE TIME STEP, RETRY
      NTRY=NTRY+1
      IF (NTRY.LE.8) GO TO 240
      WRITE (6,540)
C     LEAVE THE LAST CONVERGED CONFIGURATION ON THE LISTING -
C     THE POST-MORTEM IS WORTH MORE THAN THE CORPSE
      DO 245 J=1,N
      R(J)=RSV(J)
      F(J)=FSV(J)
      T(J)=TSV(J)
      Q(J)=QSV(J)
  245 CONTINUE
      RSTAR=RSSV
      XLSTA=XLSV
      CALL PHYSIC
      CALL PRINTM
      STOP 2
  240 DO 250 J=1,N
      R(J)=RSV(J)
      F(J)=FSV(J)
      T(J)=TSV(J)
      Q(J)=QSV(J)
  250 CONTINUE
      RSTAR=RSSV
      XLSTA=XLSV
      DT=0.5*DT
      WRITE (6,541) DT
      GO TO 220
C     CONVERGED - PRINT THE TRACK LINE
  260 AGEYR=AGEYR+DT/SECYR
      DTY2=DT/SECYR
      XLSOL=XLSTA/3.86D33
      RSOL=RSTAR/6.96D10
      TEFF=SQRT(SQRT(XLSTA/(C4PS*RSTAR*RSTAR)))
      RHOC=Q(1)**3
      PC=PP(1)**4
      WRITE (6,521) NMOD,AGEYR,DTY2,NIT,XLSOL,RSOL,TEFF,T(1),RHOC,
     1   PC,XH(1)
      IF (MOD(NMOD,NPRIN).EQ.0) CALL PRINTM
C     THE STOPPING CONVENTION OF LB93 - THE SEQUENCE ENDS WHEN
C     THE STAR HAS FADED BELOW A MILLIONTH OF THE SOLAR
C     LUMINOSITY
      IF (XLSOL.LT.1.D-6) THEN
         WRITE (6,543)
         CALL PRINTM
         STOP
      END IF
C     HELIUM IGNITION - THE PROGRAM CARRIES NO TRIPLE-ALPHA
C     REACTIONS, SO WHEN ANY PART OF THE HELIUM CORE REACHES THE
C     IGNITION TEMPERATURE THE SEQUENCE HAS FOUND THE HELIUM
C     FLASH, AND THE STORY PASSES BEYOND THIS PROGRAM.
      TMX=0.
      DO 265 J=1,N
      IF (T(J).GT.TMX) TMX=T(J)
  265 CONTINUE
      IF (TMX.GT.1.D8) THEN
         WRITE (6,544) TMX
         CALL PRINTM
         STOP
      END IF
C     TIME STEP CONTROL - GROW WHEN CONVERGENCE IS EASY, SHRINK
C     WHEN IT IS HARD, AND LIMIT THE CENTRAL HYDROGEN DEPLETION
C     TO ABOUT 3 PERCENT PER STEP
      IF (NIT.LE.5) DT=1.4*DT
C     THE SHRINK RESERVES ITSELF FOR GENUINE STRUGGLE - AT A
C     SHARP SHELL FRONT THE DAMPED ITERATION ROUTINELY NEEDS
C     FIFTEEN OR TWENTY PASSES REGARDLESS OF THE TIME STEP, AND
C     SHRINKING DT FOR A DT-INDEPENDENT DIFFICULTY ONLY
C     STRANGLES THE CLOCK.
      IF (NIT.GE.25) DT=0.7*DT
C     HOLD THE HE3 CHANGE PER STEP TO ABOUT TEN PER CENT
      IF (DX3MX.GT.0.10) DT=0.6*DT
C     HOLD THE CENTRAL TEMPERATURE CHANGE NEAR THREE PER CENT -
C     THE POST-EXHAUSTION CONTRACTION MOVES FAST
      DTC=ABS(T(1)-TSV(1))/TSV(1)
      IF (DTC.GT.0.03D0) DT=DT*0.03D0/DTC
C     TEMPORARY POINTS (HFG 1964) - REFINE THE MESH WHERE THE
C     SHELL SOURCE OR A COMPOSITION FRONT HAS STEEPENED
      CALL REMOVE(NREM)
      CALL REFINE(NADD)
      DTX=0.03*MAX(XH(1),0.02)*QHYD/MAX(EP(1),1.D-20)
C     THE CEILING SUITS THE TRILLION-YEAR REGIME OF THE LOWEST
C     MASSES - THE COMPOSITION LIMITERS BIND LONG BEFORE IT
C     ELSEWHERE
      DT=MIN(DT,DTX,3.D17)
  300 CONTINUE
      CALL PRINTM
      STOP
C
  500 FORMAT (4F10.5)
  501 FORMAT (2I5,E10.3,F10.5,E10.3,I5,F10.5,3I5)
  510 FORMAT ('1',20X,'HENYEY STELLAR EVOLUTION PROGRAM ')
  511 FORMAT (21X,'METHOD OF HENYEY, FORBES + GOULD')
  512 FORMAT (21X,'AP. J. 139, 306 (1964)')
  513 FORMAT ('0',' MASS = ',1PE11.4,'  X(H) = ',0PF7.4,'  Z =  ',
     1   F7.4)
  514 FORMAT (' N     =',I5,'  MODELS=',I5,'  DTYR=',1PE10.3)
  515 FORMAT ('0','STATIC INITIAL MODEL ',I4)
  516 FORMAT (' HE3(0)=',F9.5,'   (NEGATIVE = LOCAL EQUILIBRIUM)')
  517 FORMAT (' ALPHA =',F8.3,'   (MIXING LENGTH/SCALE HEIGHT)')
  518 FORMAT (' EOS   =  SCVH (1995) TABLES, BFGH APP. A ABOVE',
     1   ' LOG T = 7.02')
  519 FORMAT (' EOS   =  BFGH (1965) APPENDIX A THROUGHOUT')
  522 FORMAT (' OPAC  =  AJR (1983) MOLECULES+GRAINS BELOW 1.E4 K,',
     1   ' BFGH ABOVE')
  523 FORMAT (' OPAC  =  BFGH (1965) APPENDIX B + H-MINUS',
     1   ' THROUGHOUT')
  524 FORMAT (' START =  HAYASHI TRACK (PRE-MAIN-SEQUENCE',
     1   ' CONTRACTION)')
  520 FORMAT ('0','MODEL',5X,'AGE(YR)',6X,'DT(YR)',3X,'IT',3X,
     1   'L/LSUN',5X,'R/RSUN',7X,'TEFF',9X,'TC',7X,'RHOC',9X,
     2   'PC',9X,'XC')
  521 FORMAT (' ',I4,1P2E12.4,I4,1P7E11.3)
  540 FORMAT ('0NO CONVERGENCE ')
  541 FORMAT ('0TIME STEP HALVED, DT(S) =',1PE11.3)
  542 FORMAT ('0STATIC MODEL RETRIED WITH THE PSEUDOFLUX GUESS',
     1   ' NORMALIZED TO THE LUMINOSITY GUESS')
  543 FORMAT ('0SEQUENCE COMPLETE - THE STAR HAS FADED BELOW',
     1   ' 1.E-6 LSUN (THE LB93 STOPPING CONVENTION)')
  544 FORMAT ('0SEQUENCE COMPLETE - THE HELIUM CORE HAS REACHED',
     1   ' T =',1PE10.3,' K AND THE HELIUM FLASH BEGINS')
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE START - FIRST APPROXIMATION TO THE CONFIGURATION.
C     THE PAPER (SEC. V) SCALES A PREVIOUS MODEL HOMOLOGOUSLY.
C     HAVING NO PREVIOUS MODEL, THE GENERATING PROGRAM TAKES THE
C     TOTAL RADIUS AND LUMINOSITY FROM CRUDE MASS-RADIUS AND
C     MASS-LUMINOSITY RELATIONS, OBTAINS THE FITTING VALUES FROM
C     THE ENVELOPE INTEGRATION, AND MARCHES A ROUGH MODEL INWARD
C     ZONE BY ZONE WITH THE HYDROSTATIC RELATION AND THE SMALLER
C     OF THE RADIATIVE AND ADIABATIC GRADIENTS.  THE RADIUS RUN
C     IS TAKEN FROM THE MASS-RADIUS SHAPE OF THE EMDEN POLYTROPE
C     N=3 (STANDARD TABULATED VALUES).  THE RESULT NEED ONLY BE
C     GOOD ENOUGH TO START THE NEWTON-RAPHSON PROCESS.
C     ------------------------------------------------------------------
      SUBROUTINE START(TOTM,XHYD0,X3G,IBOOST)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /GRID/ XI(201),EMPT(201),EMH(201),EMPH(201),N
      COMMON /VARBL/ R(201),F(201),T(201),Q(201),XH(201),X3A(201)
      COMMON /CNOZ/ X120,X130,X140,X160
      COMMON /STRTC/ IHAY
      COMMON /CONST/ G,SIG,ARAD,RGAS,PI,C256,C4PS,C8PI
      COMMON /STARP/ XM,XMI,ZMET,QHYD
      COMMON /SURF/ RSTAR,XLSTA,DXR,DXL
      DIMENSION XLE(29),PHE(29)
C     EMDEN COORDINATE AND MASS FUNCTION PHI = -XI**2*DTHETA/DXI
C     FOR THE POLYTROPE N=3, AT INTERVALS OF 0.25
      DATA XLE/0.,.25,.50,.75,1.00,1.25,1.50,1.75,2.00,2.25,2.50,
     1   2.75,3.00,3.25,3.50,3.75,4.00,4.25,4.50,4.75,5.00,5.25,
     2   5.50,5.75,6.00,6.25,6.50,6.75,6.89685/
      DATA PHE/0.,.005112,.038710,.119605,.252129,.427603,.629801,
     1   .840957,1.045963,1.234240,1.399805,1.540418,1.656448,
     2   1.749846,1.823360,1.879998,1.922704,1.954176,1.976783,
     3   1.992547,2.003150,2.009969,2.014105,2.016422,2.017579,
     4   2.018063,2.018212,2.018235,2.018235/
      Y=1.-XHYD0-ZMET
      RMU=1.984*XHYD0+0.7495*Y+0.5*ZMET
C     MASS-RADIUS AND MASS-LUMINOSITY GUESSES (SOLAR UNITS)
      RG=6.96D10*TOTM**0.9
      XL=3.86D33*TOTM**3.5
C     THE M**3.5 LAW UNDERSTATES VERY-LOW-MASS LUMINOSITIES BY
C     FACTORS OF SEVERAL, WHICH STRANDS THE NEWTON PROCESS
C     OUTSIDE ITS BASIN.  BELOW 0.6 MSUN A SHALLOWER LAW FITTED
C     TO THE CONVERGED MODELS OF THIS PROGRAM IS USED.
      IF (TOTM.LT.0.6D0) XL=3.86D33*0.144D0*TOTM**1.86
C     HAYASHI-TRACK START - THE RADIUS FOLLOWS FROM A MEAN
C     DENSITY OF 0.005 (CENTRAL DENSITY NEAR 0.03 FOR THE
C     POLYTROPIC SHAPE), THE LUMINOSITY FROM A HAYASHI-LINE
C     EFFECTIVE TEMPERATURE OF 2900 K
      IF (IHAY.EQ.1) THEN
         RG=(3.D0*XM/(12.566371D0*5.D-3))**(1.D0/3.D0)
         XL=C4PS*RG*RG*(2.9D3)**4
      END IF
      RSTAR=RG
      XLSTA=XL
C     FITTING VALUES FROM THE ENVELOPE INTEGRATION
      CALL ENVEL(RG,XL,XHYD0,RF,TF,QF)
C     RADIUS AT EACH MESH POINT FROM THE POLYTROPIC MASS-RADIUS
C     SHAPE, RESCALED TO JOIN THE ENVELOPE AT THE FITTING POINT.
C     IN THE FIRST TABLE INTERVAL THE SERIES PHI = XI**3/3 IS
C     USED IN PLACE OF LINEAR INTERPOLATION.
      DO 20 J=1,N
      XF=EMPT(J)/XM
      TARG=XF*2.018235
      DO 12 I=1,28
      II=I
      IF (PHE(I+1).GE.TARG) GO TO 14
   12 CONTINUE
      II=28
   14 IF (II.GT.1) GO TO 16
      XIE=(3.*TARG)**0.3333333
      GO TO 18
   16 DEN=PHE(II+1)-PHE(II)
      FR=0.5
      IF (DEN.GT.1.D-5) FR=(TARG-PHE(II))/DEN
      XIE=XLE(II)+FR*(XLE(II+1)-XLE(II))
   18 R(J)=XIE
   20 CONTINUE
      RN0=R(N)
      DO 22 J=1,N
   22 R(J)=R(J)*(RF/RN0)
      R(1)=0.
      T(N)=TF
      Q(N)=QF
      F(N)=XL
C     MARCH THE PRESSURE AND TEMPERATURE INWARD ZONE BY ZONE
      C64=3./(64.*PI*SIG*G)
      PJ1=RGAS*QF**3*TF*RMU+ARAD*TF**4/3.
      NM1=N-1
      DO 60 JJ=1,NM1
      J=N-JJ
      DELM=EMPT(J+1)-EMPT(J)
      EMM=EMH(J)
      RJ1=R(J+1)
      TJ1=T(J+1)
C     HYDROSTATIC PRESSURE STEP (THE FACTORS ARE STAGED TO AVOID
C     OVERFLOW OF R**4 IN SINGLE PRECISION)
      GS=G*EMM/(RJ1*RJ1)
      P=PJ1+GS*(DELM/(12.566371*RJ1*RJ1))
C     TEMPERATURE STEP WITH THE SMALLER OF THE RADIATIVE AND
C     ADIABATIC GRADIENTS.  THE ADIABATIC ONE COMES FROM THE
C     REAL THERMODYNAMICS - WITH THE FITTING POINT AT
C     DELS = 1.E-4 THE MARCH NOW BEGINS IN THE MOLECULAR AND
C     IONIZATION ZONES, WHERE THE OLD HARDWIRED 0.40 RAN THE
C     TEMPERATURE GUESS SEVERAL TIMES TOO HOT ACROSS THE OUTER
C     DECADES AND STRANDED THE NEWTON PROCESS.
      CALL OPAC(TJ1,Q(J+1),XHYD0,ZMET,CPS,D1,D2)
      XF=EMM/XM
      XLZ=XL*XF*(2.-XF)
      GRR=C64*CPS*(XLZ/EMM)*(PJ1/TJ1**4)
      PGJ1=PJ1-ARAD*TJ1**4/3.
      IF (PGJ1.LT.0.1*PJ1) PGJ1=0.1*PJ1
      CALL THERME(PGJ1,TJ1,XHYD0,ZMET,RHD,CPD,DELD,GRA1)
      GRAD=MIN(GRR,GRA1)
      T(J)=TJ1*(P/PJ1)**GRAD
C     DENSITY FROM THE SAME THERMODYNAMICS
      PG=P-ARAD*T(J)**4/3.
      IF (PG.LT.0.1*P) PG=0.1*P
      CALL THERME(PG,T(J),XHYD0,ZMET,RHO,CPD,DELD,GRA2)
      Q(J)=RHO**0.3333333
      PJ1=P
   60 CONTINUE
C     PSEUDOFLUX GUESS FROM THE INTEGRATED NUCLEAR ENERGY RELEASE
C     OF THE MARCHED STRUCTURE, SO THAT THE ENERGY EQUATION IS
C     ROUGHLY SATISFIED FROM THE OUTSET.  THE MISMATCH WITH THE
C     LUMINOSITY GUESS AT THE FITTING POINT IS REMOVED BY THE
C     NEWTON-RAPHSON PROCESS.
      XLN=0.
      F(1)=0.
C     FOR A HAYASHI START THE LUMINOSITY IS CONTRACTION POWER,
C     UNIFORM PER GRAM - THE PSEUDOFLUX GUESS IS PROPORTIONAL TO
C     THE ENCLOSED MASS AND THE NUCLEAR INTEGRATION IS SKIPPED
      IF (IHAY.EQ.1) THEN
         DO 68 J=2,N
         F(J)=XLSTA*EMPT(J)/(XMI*XI(J)*XI(J))
   68    CONTINUE
         RETURN
      END IF
      DO 70 J=2,N
      CALL ENUC(T(J-1),Q(J-1),XHYD0,X3G,X120,X130,X140,X160,ZMET,
     1   E1,D1,D2)
      CALL ENUC(T(J),Q(J),XHYD0,X3G,X120,X130,X140,X160,ZMET,
     1   E2,D1,D2)
      XLN=XLN+0.5*(E1+E2)*(EMPT(J)-EMPT(J-1))
      F(J)=XLN/(XI(J)*XI(J))
   70 CONTINUE
C     THE MARCHED STRUCTURE IS COOLER THAN THE CONVERGED MODEL,
C     SO THE INTEGRATED EPSILON UNDERSTATES THE LUMINOSITY BY AS
C     MUCH AS TENFOLD.  FOR STARS WITH SUBSTANTIAL RADIATIVE
C     INTERIORS THE LOW AMPLITUDE CAN PUT THE FIRST CONVECTIVE
C     CLASSIFICATION (WHOSE RADIATIVE GRADIENT IS PROPORTIONAL TO
C     KAPPA TIMES F) ON THE WRONG SIDE OF THE SCHWARZSCHILD
C     BOUNDARY, AND THE NEWTON PROCESS DIVERGES; FOR FULLY
C     CONVECTIVE DWARFS THE SOFT ALL-ADIABATIC SYSTEM PREFERS THE
C     UNSCALED START.  IBOOST = 1 THEREFORE NORMALIZES THE
C     AMPLITUDE TO THE LUMINOSITY GUESS, AND THE MAIN PROGRAM
C     RETRIES A FAILED STATIC MODEL WITH THE BOOST APPLIED.
      IF (IBOOST.EQ.1 .AND. XLN.GT.0.) THEN
         SCL=XLSTA/XLN
         DO 72 J=2,N
         F(J)=F(J)*SCL
   72    CONTINUE
      END IF
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE SOLVE - ONE CONVERGED MODEL BY THE NEWTON-RAPHSON
C     (HENYEY) PROCESS.  THE LINEARIZED DIFFERENCE EQUATIONS ARE
C     REDUCED ZONE BY ZONE WITH THE RECURSION OF EQ. (44),
C          DELTA-U(J) + ALPHA(J)*DELTA-V(J) + GAMMA(J) = 0,
C     STARTING FROM ALPHA(1) = GAMMA(1) = 0 (CENTRAL CONDITION,
C     EQ. 41).  THE STORED ROWS OF EQ. (46) GIVE THE BACKWARD
C     SUBSTITUTION.  ALL CORRECTIONS ARE CARRIED IN RELATIVE FORM
C     (COLUMNS OF THE JACOBIAN SCALED BY THE CURRENT VALUES) TO
C     CONTROL THE ILL-CONDITIONING NOTED IN THE PAPER.
C     IER = 0 CONVERGED, 1 TOO MANY ITERATIONS, 2 SINGULAR MATRIX.
C     ------------------------------------------------------------------
      SUBROUTINE SOLVE(NIT,IER)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /GRID/ XI(201),EMPT(201),EMH(201),EMPH(201),N
      COMMON /VARBL/ R(201),F(201),T(201),Q(201),XH(201),X3A(201)
      COMMON /OLDT/ QN(201),EN(201),DTINV
      COMMON /THERM/ PP(201),DPT(201),DPQ(201),EE(201),DET(201),
     1   DEQ(201),CK(201),DKT(201),DKQ(201),CPA(201),EP(201),
     2   DEPT(201),DEPQ(201)
      COMMON /HENMT/ AL(2,2,201),GA(2,201),ZE(2,2,201),ET(2,2,201),
     1   BE(2,2,201),TQ(2,201),SU(2,201),SV(2,201),DU(2,201),
     2   DV(2,201)
      COMMON /FLAGS/ ICV(201)
      COMMON /CONST/ G,SIG,ARAD,RGAS,PI,C256,C4PS,C8PI
      COMMON /STARP/ XM,XMI,ZMET,QHYD
      COMMON /CTRL/ CLIM,EPSC,ITMAX,ALFA
      COMMON /SURF/ RSTAR,XLSTA,DXR,DXL
      DIMENSION AA(4,9)
      IER=0
      NM1=N-1
      DMAXP=1.
      DMNSOL=1.D30
      NMONO=0
      SGNP=0.D0
      DO 200 ITER=1,ITMAX
      CALL PHYSIC
C     LOCATE THE CONVECTIVE ZONES BY THE STABILITY CRITERION
C     (EQ. 27).  THE PLACING OF THESE BOUNDARIES IS THE MOST
C     TROUBLESOME PART OF THE METHOD (SEC. IV OF THE PAPER).  IN
C     PLACE OF THE INTERPOLATION AMONG COMPLETE MODELS (FIG. 1)
C     A SIMPLER DEVICE IS USED HERE - AFTER THE EARLY ITERATIONS
C     A ZONE IS RECLASSIFIED ONLY WHEN THE CRITERION IS EXCEEDED
C     BY A DEFINITE MARGIN, AND THE PATTERN IS FROZEN ENTIRELY
C     ONCE THE ITERATION IS WELL ADVANCED, TO PREVENT AN
C     OSCILLATORY INSTABILITY OF THE BOUNDARY.
C     THE CLASSIFICATION IS ALWAYS HYSTERETIC AGAINST THE
C     STANDING FLAGS - ACROSS ITERATIONS AND ACROSS TIME STEPS -
C     SO A MARGINAL ZONE AT A SHELL FRONT CANNOT FLIP THE PATTERN
C     EVERY STEP AND CONVINCE THE TIME-STEP CONTROL THAT THE
C     PROBLEM IS HARD.  THE FRESH (MODE 0) CLASSIFICATION IS DONE
C     ONCE, AFTER THE FIRST APPROXIMATION.
      IF (ITER.LE.12) CALL CONVCK(1)
C     SCALES FOR THE RELATIVE CORRECTIONS
      FLR=1.D-6*ABS(F(N))
      IF (FLR.LE.0.) FLR=1.
      DO 25 J=1,N
      SU(1,J)=R(J)
      IF (SU(1,J).LE.0.) SU(1,J)=1.
      SU(2,J)=ABS(F(J))
      IF (SU(2,J).LT.FLR) SU(2,J)=FLR
      SV(1,J)=T(J)
      SV(2,J)=Q(J)
   25 CONTINUE
C     CENTRAL BOUNDARY CONDITION, EQ. (41) - DELTA-U(1) = 0
      DO 28 K=1,2
      GA(K,1)=0.
      DO 28 L=1,2
   28 AL(L,K,1)=0.
C
C     FORWARD ELIMINATION OVER THE ZONES
      DO 100 J=1,NM1
      CALL ZONEQ(J,AA)
C     SCALE THE COLUMNS BY THE CURRENT VALUES OF THE VARIABLES
      DO 32 I=1,4
      AA(I,1)=AA(I,1)*SU(1,J)
      AA(I,2)=AA(I,2)*SU(2,J)
      AA(I,3)=AA(I,3)*SV(1,J)
      AA(I,4)=AA(I,4)*SV(2,J)
      AA(I,5)=AA(I,5)*SU(1,J+1)
      AA(I,6)=AA(I,6)*SU(2,J+1)
      AA(I,7)=AA(I,7)*SV(1,J+1)
      AA(I,8)=AA(I,8)*SV(2,J+1)
   32 CONTINUE
C     ELIMINATE DELTA-U(J) BY THE RECURSION, EQ. (44)
      DO 34 I=1,4
      AA(I,9)=AA(I,9)-AA(I,1)*GA(1,J)-AA(I,2)*GA(2,J)
   34 CONTINUE
      DO 36 I=1,4
      DO 36 K=1,2
   36 AA(I,2+K)=AA(I,2+K)-AA(I,1)*AL(1,K,J)-AA(I,2)*AL(2,K,J)
C     NORMALIZE EACH ROW BY ITS LARGEST COEFFICIENT
      DO 44 I=1,4
      BIG=0.
      DO 40 K=3,8
      IF (ABS(AA(I,K)).GT.BIG) BIG=ABS(AA(I,K))
   40 CONTINUE
      IF (BIG.GT.0.) GO TO 42
      IER=2
      WRITE (6,542) J
      RETURN
   42 BIG=1./BIG
      DO 43 K=3,9
   43 AA(I,K)=AA(I,K)*BIG
   44 CONTINUE
C     GAUSSIAN ELIMINATION OF DELTA-V(J) (COLUMNS 3 AND 4) WITH
C     ROW INTERCHANGES
      DO 60 KC=1,2
      IC=KC+2
      IP=KC
      BIG=ABS(AA(KC,IC))
      KP1=KC+1
      DO 46 I=KP1,4
      IF (ABS(AA(I,IC)).LE.BIG) GO TO 46
      BIG=ABS(AA(I,IC))
      IP=I
   46 CONTINUE
      IF (IP.EQ.KC) GO TO 50
      DO 48 K=3,9
      TMP=AA(KC,K)
      AA(KC,K)=AA(IP,K)
      AA(IP,K)=TMP
   48 CONTINUE
   50 IF (ABS(AA(KC,IC)).GT.1.D-12) GO TO 52
      IER=2
      WRITE (6,542) J
      RETURN
   52 DO 56 I=KP1,4
      FAC=AA(I,IC)/AA(KC,IC)
      DO 54 K=IC,9
   54 AA(I,K)=AA(I,K)-FAC*AA(KC,K)
   56 CONTINUE
   60 CONTINUE
C     STORE ROWS 1-2 FOR THE BACKWARD SUBSTITUTION (EQ. 46)
      DO 64 L=1,2
      TQ(L,J)=AA(L,9)
      DO 64 K=1,2
      ZE(L,K,J)=AA(L,2+K)
      ET(L,K,J)=AA(L,4+K)
      BE(L,K,J)=AA(L,6+K)
   64 CONTINUE
C     ROWS 3-4 GIVE ALPHA AND GAMMA AT J+1 (EQ. 45)
      C11=AA(3,5)
      C12=AA(3,6)
      C21=AA(4,5)
      C22=AA(4,6)
      DET2=C11*C22-C12*C21
      IF (ABS(DET2).GT.1.D-20) GO TO 66
      IER=2
      WRITE (6,542) J
      RETURN
   66 AL(1,1,J+1)=(C22*AA(3,7)-C12*AA(4,7))/DET2
      AL(1,2,J+1)=(C22*AA(3,8)-C12*AA(4,8))/DET2
      AL(2,1,J+1)=(C11*AA(4,7)-C21*AA(3,7))/DET2
      AL(2,2,J+1)=(C11*AA(4,8)-C21*AA(3,8))/DET2
      GA(1,J+1)=(C22*AA(3,9)-C12*AA(4,9))/DET2
      GA(2,J+1)=(C11*AA(4,9)-C21*AA(3,9))/DET2
  100 CONTINUE
C
C     OUTER BOUNDARY - THE FITTING CONDITIONS, EQS. (37)-(38) AND
C     (42)-(43).  THE OUTER ENVELOPE (MASS FRACTION DELS) IS
C     INTEGRATED SEPARATELY AS A FUNCTION OF THE TOTAL RADIUS AND
C     LUMINOSITY, GIVING THE FITTED QUANTITIES OF EQS. (30)-(33).
C     THE PAPER INTERPOLATES AMONG FOUR STORED ATMOSPHERE CASES
C     (FIG. 4) - HERE THE INTEGRATION IS SIMPLY REPEATED AND THE
C     PARTIAL DERIVATIVES ARE OBTAINED BY DIFFERENCING.
C     THE PERTURBATION IS KEPT SMALL - NEAR THE TIP OF THE GIANT
C     BRANCH THE FITTED DENSITY FALLS SIXTY-FOLD ACROSS A FIVE
C     PERCENT CHANGE OF RADIUS, AND A BROAD SECANT MISREADS SO
C     CURVED A RESPONSE BADLY ENOUGH TO SET THE SURFACE NEWTON
C     CYCLING.  (THE MARCH IS SUBSTEPPED AND SMOOTH, SO A NARROW
C     DIFFERENCE IS SAFE.)
      CALL ENVEL(RSTAR,XLSTA,XH(N),RF0,TF0,QF0)
      DH=0.005
      CALL ENVEL(RSTAR*(1.+DH),XLSTA,XH(N),RF1,TF1,QF1)
      CALL ENVEL(RSTAR,XLSTA*(1.+DH),XH(N),RF2,TF2,QF2)
      FJ11=(RF1-RF0)/DH
      FJ12=(RF2-RF0)/DH
      FJ31=(TF1-TF0)/DH
      FJ32=(TF2-TF0)/DH
      FJ41=(QF1-QF0)/DH
      FJ42=(QF2-QF0)/DH
      SR1=R(N)-RF0
      SR2=F(N)-XLSTA
      SR3=T(N)-TF0
      SR4=Q(N)-QF0
      S1=SU(1,N)
      S2=SU(2,N)
      S3=SV(1,N)
      S4=SV(2,N)
C     SUBSTITUTE THE LINEARIZED FITTING RELATIONS INTO THE
C     RECURSION (44) AT J = N AND SOLVE FOR THE RELATIVE CHANGES
C     OF THE TOTAL RADIUS AND LUMINOSITY
      A11=FJ11/S1+AL(1,1,N)*FJ31/S3+AL(1,2,N)*FJ41/S4
      A12=FJ12/S1+AL(1,1,N)*FJ32/S3+AL(1,2,N)*FJ42/S4
      B1=SR1/S1+AL(1,1,N)*SR3/S3+AL(1,2,N)*SR4/S4-GA(1,N)
      A21=AL(2,1,N)*FJ31/S3+AL(2,2,N)*FJ41/S4
      A22=XLSTA/S2+AL(2,1,N)*FJ32/S3+AL(2,2,N)*FJ42/S4
      B2=SR2/S2+AL(2,1,N)*SR3/S3+AL(2,2,N)*SR4/S4-GA(2,N)
      DET2=A11*A22-A12*A21
      IF (ABS(DET2).GT.1.D-20) GO TO 120
      IER=2
      WRITE (6,542) N
      RETURN
  120 DXR=(B1*A22-B2*A12)/DET2
      DXL=(B2*A11-B1*A21)/DET2
      DV(1,N)=(FJ31*DXR+FJ32*DXL-SR3)/S3
      DV(2,N)=(FJ41*DXR+FJ42*DXL-SR4)/S4
      DU(1,N)=(FJ11*DXR+FJ12*DXL-SR1)/S1
      DU(2,N)=(XLSTA*DXL-SR2)/S2
C
C     BACKWARD SUBSTITUTION, EQS. (46) AND (44), FOR DECREASING J
      DO 140 JJ=1,NM1
      J=N-JJ
      T1=TQ(1,J)+ET(1,1,J)*DU(1,J+1)+ET(1,2,J)*DU(2,J+1)
     1   +BE(1,1,J)*DV(1,J+1)+BE(1,2,J)*DV(2,J+1)
      T2=TQ(2,J)+ET(2,1,J)*DU(1,J+1)+ET(2,2,J)*DU(2,J+1)
     1   +BE(2,1,J)*DV(1,J+1)+BE(2,2,J)*DV(2,J+1)
      IF (ABS(ZE(2,2,J)).GT.1.D-20 .AND. ABS(ZE(1,1,J)).GT.1.D-20)
     1   GO TO 130
      IER=2
      WRITE (6,542) J
      RETURN
  130 DV(2,J)=-T2/ZE(2,2,J)
      DV(1,J)=-(T1+ZE(1,2,J)*DV(2,J))/ZE(1,1,J)
      DU(1,J)=-AL(1,1,J)*DV(1,J)-AL(1,2,J)*DV(2,J)-GA(1,J)
      DU(2,J)=-AL(2,1,J)*DV(1,J)-AL(2,2,J)*DV(2,J)-GA(2,J)
  140 CONTINUE
C
C     LARGEST RELATIVE CORRECTION.  FOLLOWING THE PAPER (SEC. V),
C     DELTA-F/F IS EXAMINED ONLY AT THE SURFACE, SINCE F MAY PASS
C     THROUGH ZERO AT INTERIOR POINTS.
      DMAX=0.
      JMX=0
      KMX=1
      DO 150 J=1,N
      IF (J.GT.1 .AND. ABS(DU(1,J)).GT.DMAX) THEN
         DMAX=ABS(DU(1,J))
         JMX=J
         KMX=1
      END IF
      IF (ABS(DV(1,J)).GT.DMAX) THEN
         DMAX=ABS(DV(1,J))
         JMX=J
         KMX=2
      END IF
      IF (ABS(DV(2,J)).GT.DMAX) THEN
         DMAX=ABS(DV(2,J))
         JMX=J
         KMX=3
      END IF
  150 CONTINUE
      IF (ABS(DU(2,N)).GT.DMAX) THEN
         DMAX=ABS(DU(2,N))
         JMX=N
         KMX=4
      END IF
      IF (ABS(DXR).GT.DMAX) THEN
         DMAX=ABS(DXR)
         JMX=N
         KMX=5
      END IF
      IF (ABS(DXL).GT.DMAX) THEN
         DMAX=ABS(DXL)
         JMX=N
         KMX=6
      END IF
C     LIMIT THE INCREMENTS (SEC. V OF THE PAPER)
      DAMP=1.
      IF (DMAX.GT.CLIM) DAMP=CLIM/DMAX
C     THE SURFACE FIT OF A STAR CROSSING OUT OF THE GIANT REGION
C     CAN OFFER TWO NEARBY ENVELOPE SOLUTIONS (THE SURFACE
C     CONVECTION ZONE OF THE COOL BRANCH IS DYING), AND AN
C     UNDAMPED NEWTON LEAPS BETWEEN THE BASINS FOREVER - A
C     DIFFICULTY NO TIME STEP CAN CURE, SINCE THE ENVELOPE
C     CARRIES NO TIME TERMS.  ON EVOLUTIONARY STEPS THE TOTAL
C     RADIUS AND LUMINOSITY ARE THEREFORE HELD TO A FEW PERCENT
C     PER ITERATION, SO THE ITERATION SETTLES INTO THE BASIN IT
C     STARTED IN.  BUT A HYDROGEN SHELL FLASH IS A GENUINE
C     RUNAWAY - THE SOLUTION'S LUMINOSITY REALLY IS FAR AWAY,
C     AND THE CORRECTION ASKS FOR IT WITH THE SAME SIGN EVERY
C     ITERATION, WHERE BASIN-LEAPING ALTERNATES.  A PERSISTENTLY
C     ONE-SIGNED SURFACE CORRECTION IS THEREFORE ALLOWED AN
C     EXPONENTIALLY GROWING ALLOWANCE, SO THE FLASH CAN BE
C     FOLLOWED WHILE THE FOLD STAYS PINNED.
      IF (DTINV.GT.0.) THEN
         SGN=SIGN(1.D0,DXL)
         IF (SGN.EQ.SGNP .AND. ITER.GT.1) THEN
            NMONO=NMONO+1
         ELSE
            NMONO=0
         END IF
         SGNP=SGN
         CAPS=0.05D0*2.D0**MIN(NMONO,6)
         SURFC=MAX(ABS(DXR),ABS(DXL))
         IF (DAMP*SURFC.GT.CAPS) DAMP=CAPS/SURFC
      END IF
C     A SHARP COMPOSITION FRONT CAN SET UP AN UNDAMPED NEWTON
C     TWO-CYCLE - THE CORRECTIONS ALTERNATE BETWEEN TWO STATES
C     WITHOUT SHRINKING.  WHEN THE CORRECTIONS STAGNATE, HALVING
C     THE APPLIED STEP COLLAPSES THE CYCLE ONTO ITS MIDPOINT.
C     THE MEASURE IS THE BEST CORRECTION SEEN SO FAR, NOT MERELY
C     THE PREVIOUS ONE - THE CURVED SURFACE RESPONSE OF A GIANT
C     SETS UP THREE- AND FOUR-CYCLES THAT A CONSECUTIVE
C     COMPARISON NEVER CATCHES.
      IF (ITER.GT.8 .AND. DMAX.GT.0.7D0*DMNSOL) DAMP=0.5D0*DAMP
      DO 160 J=1,N
      R(J)=R(J)+DAMP*SU(1,J)*DU(1,J)
      F(J)=F(J)+DAMP*SU(2,J)*DU(2,J)
      T(J)=T(J)+DAMP*SV(1,J)*DV(1,J)
      Q(J)=Q(J)+DAMP*SV(2,J)*DV(2,J)
  160 CONTINUE
      RSTAR=RSTAR*(1.+DAMP*DXR)
      XLSTA=XLSTA*(1.+DAMP*DXL)
      WRITE (6,530) ITER,DMAX,DAMP,JMX,KMX
      DMAXP=DMAX
      IF (DMAX.LT.DMNSOL) DMNSOL=DMAX
      IF (DMAX.LT.EPSC) GO TO 210
      IF (ITER.GE.20 .AND. DMAX.LT.20.*EPSC) GO TO 210
  200 CONTINUE
      IER=1
      NIT=ITMAX
      RETURN
  210 NIT=ITER
      CALL PHYSIC
      RETURN
  530 FORMAT (' ITER=',I3,'  MAX CORRECT=',1PE10.2,'  DAMP=',
     1   0PF6.3,'  J=',I3,'  K=',I1)
  542 FORMAT ('0SINGULAR MATRIX AT ZONE ',I4)
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE PHYSIC - THE MATERIAL FUNCTIONS P, E, K, EPSILON
C     AND THEIR PARTIAL DERIVATIVES WITH RESPECT TO T AND Q AT
C     EVERY MESH POINT (SECOND BOX OF FIG. 2).
C     ------------------------------------------------------------------
      SUBROUTINE PHYSIC
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /GRID/ XI(201),EMPT(201),EMH(201),EMPH(201),N
      COMMON /VARBL/ R(201),F(201),T(201),Q(201),XH(201),X3A(201)
      COMMON /CNOC/ X12A(201),X13A(201),X14A(201),X16A(201)
      COMMON /CNOZ/ X120,X130,X140,X160
      COMMON /SURF/ RSTAR,XLSTA,DXR,DXL
      COMMON /STRTC/ IHAY
      COMMON /THERM/ PP(201),DPT(201),DPQ(201),EE(201),DET(201),
     1   DEQ(201),CK(201),DKT(201),DKQ(201),CPA(201),EP(201),
     2   DEPT(201),DEPQ(201)
      COMMON /CONST/ G,SIG,ARAD,RGAS,PI,C256,C4PS,C8PI
      COMMON /STARP/ XM,XMI,ZMET,QHYD
      XINRT=ZMET-X120-X130-X140-X160
      DO 10 J=1,N
C     MOLES PER GRAM OF IONS AND OF FREE ELECTRONS IN THE FULLY
C     IONIZED MIXTURE.  HE4 COMES FROM THE SUM RULE (C23) OVER
C     THE EXPLICIT SPECIES PLUS THE INERT REMAINDER OF Z.
      CNOJ=X12A(J)+X13A(J)+X14A(J)+X16A(J)
      X4J=MAX(1.-XH(J)-X3A(J)-CNOJ-XINRT,0.D0)
      ANUI=0.9921*XH(J)+0.3316*X3A(J)+0.2498*X4J
     1   +0.0714*CNOJ+0.04*XINRT
      ANUE=0.9921*XH(J)+0.6631*X3A(J)+0.4997*X4J
     1   +0.5*CNOJ+0.458*XINRT
      CALL STATE(T(J),Q(J),XH(J),ANUI,ANUE,PP(J),DPT(J),DPQ(J),
     1   EE(J),DET(J),DEQ(J))
      CALL OPAC(T(J),Q(J),XH(J),ZMET,CPA(J),DCT,DCQ)
C     THE MODIFIED OPACITY VARIABLE K OF EQ. (11)
      CK(J)=3.*CPA(J)*PP(J)**3/(C256*T(J)**3)
      DKT(J)=CK(J)*(DCT/CPA(J)+3.*DPT(J)/PP(J)-3./T(J))
      DKQ(J)=CK(J)*(DCQ/CPA(J)+3.*DPQ(J)/PP(J))
      CALL ENUC(T(J),Q(J),XH(J),X3A(J),X12A(J),X13A(J),X14A(J),
     1   X16A(J),ZMET,EP(J),DEPT(J),DEPQ(J))
C     DURING THE HAYASHI-START STATIC SOLVE, A UNIFORM ARTIFICIAL
C     ENERGY GENERATION L/M STANDS IN FOR THE CONTRACTION POWER
C     (IT CARRIES NO T,Q DERIVATIVES).  THE FLAG DROPS AFTER THE
C     INITIAL MODEL CONVERGES.
      IF (IHAY.EQ.1) EP(J)=EP(J)+XLSTA/XM
   10 CONTINUE
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE CONVCK - STABILITY AGAINST CONVECTION FOR EACH
C     ZONE (EQ. 27).  THE ZONE IS CONVECTIVE WHEN THE RADIATIVE
C     GRADIENT DLOG(T)/DLOG(P) EXCEEDS THE ADIABATIC VALUE 0.40.
C     WHERE CONVECTIVE, THE ADIABATIC CONDITION (EQ. 26) REPLACES
C     THE RADIATIVE CONDITION (EQ. 25) IN THE DIFFERENCE SYSTEM.
C     FOR MODE = 1 A ZONE IS RECLASSIFIED ONLY WHEN THE CRITERION
C     IS PASSED BY A TEN PER CENT MARGIN (HYSTERESIS), WHICH
C     SUPPRESSES THE FLUTTER OF THE CONVECTIVE BOUNDARIES DURING
C     THE ITERATION.
C     ------------------------------------------------------------------
      SUBROUTINE CONVCK(MODE)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /GRID/ XI(201),EMPT(201),EMH(201),EMPH(201),N
      COMMON /VARBL/ R(201),F(201),T(201),Q(201),XH(201),X3A(201)
      COMMON /THERM/ PP(201),DPT(201),DPQ(201),EE(201),DET(201),
     1   DEQ(201),CK(201),DKT(201),DKQ(201),CPA(201),EP(201),
     2   DEPT(201),DEPQ(201)
      COMMON /FLAGS/ ICV(201)
      COMMON /CONST/ G,SIG,ARAD,RGAS,PI,C256,C4PS,C8PI
      COMMON /STARP/ XM,XMI,ZMET,QHYD
      NM1=N-1
      C64=3./(64.*PI*SIG*G)
      DO 10 J=1,NM1
      TB=0.5*(T(J)+T(J+1))
      PB=(0.5*(PP(J)+PP(J+1)))**4
      CB=0.5*(CPA(J)+CPA(J+1))
      XB=0.5*(XI(J)+XI(J+1))
      FB=0.5*(F(J)+F(J+1))
      XLB=XB*XB*FB
      GR=C64*CB*(XLB/EMH(J))*(PB/TB**4)
      IF (MODE.EQ.1) GO TO 5
      ICV(J)=0
      IF (GR.GT.0.40) ICV(J)=1
      GO TO 10
    5 IF (GR.GT.0.44) ICV(J)=1
      IF (GR.LT.0.36) ICV(J)=0
   10 CONTINUE
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE ZONEQ - THE FOUR DIFFERENCE EQUATIONS OF THE ZONE
C     BETWEEN POINTS J AND J+1, EQS. (22), (23), (24), AND (25) OR
C     (26), WITH THEIR PARTIAL DERIVATIVES (THE TENSORS OF EQS.
C     39-40).  AA(I,1-8) = DERIVATIVES WITH RESPECT TO R,F,T,Q AT
C     J AND AT J+1.  AA(I,9) = THE RESIDUAL.  THE DERIVATIVES WITH
C     RESPECT TO T AND Q INCLUDE THE IMPLICIT VARIATION THROUGH
C     P(T,Q), E(T,Q), K(T,Q), AND EPSILON(T,Q).
C     ------------------------------------------------------------------
      SUBROUTINE ZONEQ(J,AA)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      DIMENSION AA(4,9)
      COMMON /GRID/ XI(201),EMPT(201),EMH(201),EMPH(201),N
      COMMON /VARBL/ R(201),F(201),T(201),Q(201),XH(201),X3A(201)
      COMMON /OLDT/ QN(201),EN(201),DTINV
      COMMON /THERM/ PP(201),DPT(201),DPQ(201),EE(201),DET(201),
     1   DEQ(201),CK(201),DKT(201),DKQ(201),CPA(201),EP(201),
     2   DEPT(201),DEPQ(201)
      COMMON /FLAGS/ ICV(201)
      COMMON /CONST/ G,SIG,ARAD,RGAS,PI,C256,C4PS,C8PI
      COMMON /STARP/ XM,XMI,ZMET,QHYD
      J1=J
      J2=J+1
      X1=XI(J1)
      X2=XI(J2)
      XS=X1+X2
      XD=X2-X1
      RS=R(J1)+R(J2)
      RD=R(J2)-R(J1)
      PS=PP(J1)+PP(J2)
      PD=PP(J2)-PP(J1)
      QS=Q(J1)+Q(J2)
      QD=Q(J2)-Q(J1)
      DO 10 I=1,4
      DO 10 K=1,9
   10 AA(I,K)=0.
C
C     EQUATION (22) - HYDROSTATIC EQUILIBRIUM
      WR=G*EMH(J)*(QS/PS)**3/(RS*RS)
      W=WR*RD
      AA(1,1)=-WR-2.*W/RS
      AA(1,5)=WR-2.*W/RS
      CP1=-1.-3.*W/PS
      CP2=1.-3.*W/PS
      AA(1,3)=CP1*DPT(J1)
      AA(1,4)=CP1*DPQ(J1)+3.*W/QS
      AA(1,7)=CP2*DPT(J2)
      AA(1,8)=CP2*DPQ(J2)+3.*W/QS
      AA(1,9)=PD+W
C
C     EQUATION (23) - MASS CONTINUITY
      QS3=QS**3
      AA(2,1)=QS3*RS*(RS-2.*RD)
      AA(2,5)=-QS3*RS*(RS+2.*RD)
      AA(2,4)=-3.*QS*QS*RS*RS*RD
      AA(2,8)=AA(2,4)
      AA(2,9)=C8PI*EMPH(J)*XD-QS3*RS*RS*RD
C
C     EQUATION (24) - ENERGY BALANCE WITH BACKWARD TIME
C     DIFFERENCES.  THE NUCLEAR RATE ENTERS AS THE GEOMETRIC MEAN
C     OF THE VALUES AT THE TWO POINTS.
      A4=3.*(PS/QS)**4
      A4P=4.*A4/PS
      A4Q=4.*A4/QS
      E1=EP(J1)
      E2=EP(J2)
      GE=0.
      GT1=0.
      GQ1=0.
      GT2=0.
      GQ2=0.
      IF (E1.LE.1.D-15 .OR. E2.LE.1.D-15) GO TO 20
      GE=2.*SQRT(E1*E2)
      GT1=0.5*GE*DEPT(J1)/E1
      GQ1=0.5*GE*DEPQ(J1)/E1
      GT2=0.5*GE*DEPT(J2)/E2
      GQ2=0.5*GE*DEPQ(J2)/E2
   20 CONTINUE
      DQT=Q(J1)+Q(J2)-QN(J1)-QN(J2)
      BR=GE-(EE(J1)+EE(J2)-EN(J1)-EN(J2))*DTINV+A4*DQT*DTINV
      CM=2.*EMPH(J)*XD
      BT1=GT1-DET(J1)*DTINV+A4P*DPT(J1)*DQT*DTINV
      BQ1=GQ1-DEQ(J1)*DTINV+(A4P*DPQ(J1)-A4Q)*DQT*DTINV+A4*DTINV
      BT2=GT2-DET(J2)*DTINV+A4P*DPT(J2)*DQT*DTINV
      BQ2=GQ2-DEQ(J2)*DTINV+(A4P*DPQ(J2)-A4Q)*DQT*DTINV+A4*DTINV
      AA(3,2)=XS*(X2-3.*X1)
      AA(3,6)=XS*(3.*X2-X1)
      AA(3,3)=-CM*BT1
      AA(3,4)=-CM*BQ1
      AA(3,7)=-CM*BT2
      AA(3,8)=-CM*BQ2
      AA(3,9)=F(J2)*XS*(3.*X2-X1)+F(J1)*XS*(X2-3.*X1)-CM*BR
C
      IF (ICV(J).EQ.1) GO TO 40
C
C     EQUATION (25) - RADIATIVE TRANSPORT
      CKS=CK(J1)+CK(J2)
      FS=F(J1)+F(J2)
      CW=XS*XS/EMH(J)
      CWF=CW*FS
      AA(4,2)=-CKS*CW*PD
      AA(4,6)=AA(4,2)
      AA(4,3)=-1.-CWF*(DKT(J1)*PD-CKS*DPT(J1))
      AA(4,7)=1.-CWF*(DKT(J2)*PD+CKS*DPT(J2))
      AA(4,4)=-CWF*(DKQ(J1)*PD-CKS*DPQ(J1))
      AA(4,8)=-CWF*(DKQ(J2)*PD+CKS*DPQ(J2))
      AA(4,9)=T(J2)-T(J1)-CKS*CWF*PD
      GO TO 50
C
C     EQUATION (26) - CONVECTIVE (ADIABATIC) TRANSPORT
   40 AA(4,3)=-DET(J1)-A4P*DPT(J1)*QD
      AA(4,7)=DET(J2)-A4P*DPT(J2)*QD
      AA(4,4)=-DEQ(J1)-(A4P*DPQ(J1)-A4Q)*QD+A4
      AA(4,8)=DEQ(J2)-(A4P*DPQ(J2)-A4Q)*QD-A4
      AA(4,9)=EE(J2)-EE(J1)-A4*QD
   50 RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE ENVEL - THE OUTER-ZONE (ENVELOPE) INTEGRATION,
C     TAKING THE PLACE OF THE ATMOSPHERE PROGRAM OF M. S. VARDYA
C     REFERRED TO IN THE PAPER.  GIVEN THE TOTAL RADIUS RS AND
C     LUMINOSITY XLS, THE FLUX TEMPERATURE FOLLOWS FROM
C          TF**4 = L/(4*PI*SIGMA*R**2)
C     (HVB 1965, EQ. 8).  THE OUTERMOST LAYERS ARE IN RADIATIVE
C     EQUILIBRIUM AND FOLLOW THE BLANKETED T-TAU RELATION OF
C     HENYEY, VARDYA + BODENHEIMER (1965, AP. J. 142, 841),
C     EQ. (10) WITH THE COEFFICIENTS OF EQS. (11)-(12) AND THE
C     METAL SCALING ZETA OF EQ. (9) - SEE SUBROUTINE TTAU.  THIS
C     LAYER IS INTEGRATED IN OPTICAL DEPTH FROM TAU = 0.01 WITH
C     THE HYDROSTATIC RELATION DP = (G/KAPPA)*DTAU, DOWN TO THE
C     ONSET OF CONVECTION (WHERE THE GRADIENT ALONG THE RELATION
C     FIRST REACHES THE ADIABATIC ONE) OR TO TAU NEAR 50.  FROM
C     THERE THE ENVELOPE (MASS FRACTION DELS OF THE STAR, WITH
C     L TAKEN CONSTANT AND THE TIME TERMS NEGLECTED) IS
C     INTEGRATED INWARD ON A LOGARITHMIC COLUMN-MASS SCALE WITH
C     THE HYDROSTATIC RELATION AND THE SMALLER OF THE RADIATIVE
C     AND MIXING-LENGTH GRADIENTS, THE THERMODYNAMICS COMING FROM
C     THE SAHA IONIZATION EQUILIBRIUM.  RETURNED ARE THE FITTED
C     VALUES OF EQS. (30), (32), (33) AT THE OUTERMOST INTERIOR
C     POINT - RF (RADIUS), TF (TEMPERATURE), QF (CUBE ROOT OF
C     DENSITY).
C     ------------------------------------------------------------------
      SUBROUTINE ENVEL(RS,XLS,XSU,RF,TF,QF)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /CONST/ G,SIG,ARAD,RGAS,PI,C256,C4PS,C8PI
      COMMON /STARP/ XM,XMI,ZMET,QHYD
      COMMON /CTRL/ CLIM,EPSC,ITMAX,ALFA
      COMMON /EOSC/ IEOS,IOPC
      TE=SQRT(SQRT(XLS/(C4PS*RS*RS)))
      TE4=TE**4
C     BLANKETING COEFFICIENTS, HVB (1965) EQS. (9), (11), (12).
C     THE PARENTHETICAL (1.E-4*TF - 1.1) IS HELD AT 0.4 ABOVE
C     15000 K, AS PRESCRIBED.  THE SOLAR METAL-TO-HYDROGEN RATIO
C     OF EQ. (9) IS TAKEN AT X = 0.708, Z = 0.020.
      T4K=1.D-4*TE
      BSE=T4K-1.1
      IF (BSE.GT.0.4) BSE=0.4
      B4=BSE*BSE*BSE*BSE
      ABLK=(0.6379*B4+0.02565)*TE4
      CBLK=1./(5.465-2.087*T4K)
      IF (T4K.GE.0.98) CBLK=1./(2.68*T4K+0.79)
      BBLK=(0.5146*B4+0.4605-CBLK)*TE4
      ZETA=SQRT(35.4*ZMET/XSU)
C     THE LB93 CASE-B ATMOSPHERE IS A GREY RADIATIVE MODEL - WITH
C     THE SCVH PHYSICS SELECTED THE BLANKETING TERMS ARE DROPPED,
C     AND THE RELATION REDUCES TO BOEHM-VITENSE'S FIT TO THE
C     EXACT GREY HOPF FUNCTION.  THE LEGACY PATH KEEPS THE FULL
C     HVB (1965) BLANKETED LAW.
      IF (IEOS.EQ.0) ZETA=0.D0
C     STARTING POINT OF THE RADIATIVE LAYER, P = G*TAU/KAPPA,
C     WITH THE DENSITY FROM A SHORT FIXED-POINT ITERATION
      TAU=0.01
      CALL TTAU(TAU,TE4,ZETA,ABLK,BBLK,T4X,DT4)
      TX=SQRT(SQRT(T4X))
      R3=RS**3
      GS=G*XM/(RS*RS)
      RHO=1.D-11
      DO 10 I=1,25
      CALL OPAC(TX,RHO**0.3333333,XSU,ZMET,CPS,D1,D2)
      P=GS*TAU/CPS
      PG=P-ARAD*T4X/3.
      IF (PG.LT.0.1*P) PG=0.1*P
      CALL THERME(PG,TX,XSU,ZMET,RHN,CPD,DELD,GRADA)
      RHO=SQRT(RHO*RHN)
   10 CONTINUE
      XMU=12.566371*RS*RS*P/GS
C     MARCH OF THE RADIATIVE LAYER - TWENTY-FIVE LOGARITHMIC STEPS
C     PER DECADE OF OPTICAL DEPTH, EACH WITH ONE CORRECTOR PASS
C     FOR THE STEEP H-MINUS OPACITY.  TAUP IS THE EFFECTIVE
C     (SPHERICAL) DEPTH OF HVB EQ. (7).
      TAUP=TAU
      DO 20 K=1,93
      TAUN=TAU*1.0964782
      DTAU=TAUN-TAU
      R23=R3**0.6666667
      GLOC=G*XM/R23
      SPH=RS*RS/R23
      CALL OPAC(TX,RHO**0.3333333,XSU,ZMET,CPS,D1,D2)
      TAUPN=TAUP+SPH*DTAU
      CALL TTAU(TAUPN,TE4,ZETA,ABLK,BBLK,T4N,DT4)
      TN=SQRT(SQRT(T4N))
      PN=P+GLOC*DTAU/CPS
      PG=PN-ARAD*T4N/3.
      IF (PG.LT.0.1*PN) PG=0.1*PN
      CALL THERME(PG,TN,XSU,ZMET,RHN,CPD,DELD,GRADA)
      CALL OPAC(TN,RHN**0.3333333,XSU,ZMET,CPN,D1,D2)
      PN=P+GLOC*DTAU*0.5*(1./CPS+1./CPN)
      PG=PN-ARAD*T4N/3.
      IF (PG.LT.0.1*PN) PG=0.1*PN
      CALL THERME(PG,TN,XSU,ZMET,RHN,CPD,DELD,GRADA)
C     ONSET OF CONVECTION - THE GRADIENT ALONG THE RELATION,
C     D LN T / D LN P = P*KAPPA*(R0/R)**2*(DT4/DTAU)/(4*T**4*G),
C     TESTED AGAINST THE ADIABATIC GRADIENT
      GRREL=PN*CPN*SPH*DT4/(4.*T4N*GLOC)
      IF (GRREL.GE.GRADA) GO TO 25
      DR=DTAU/(CPN*RHN)
      XMU=XMU+12.566371*R23*RHN*DR
      R3=R3-3.*R23*DR
      P=PN
      TX=TN
      RHO=RHN
      TAU=TAUN
      TAUP=TAUPN
   20 CONTINUE
   25 CONTINUE
      C64=3./(64.*PI*SIG*G)
      DELME=XM-XMI
      NE=280
C     INWARD MARCH ON A LOGARITHMIC SCALE OF EXTERIOR COLUMN
C     MASS, TAKEN UP AT THE COLUMN MASS REACHED BY THE RADIATIVE
C     LAYER
      XL0=LOG10(XMU/DELME)
      IF (XL0.LT.-9.) XL0=-9.
      IF (XL0.GT.-0.1) GO TO 45
      DO 40 K=1,NE
      XMUN=DELME*10.**(XL0*(1.-DBLE(K)/DBLE(NE)))
      DMU=XMUN-XMU
C     THE ZONE IS TAKEN IN SUBSTEPS SMALL ENOUGH THAT THE
C     TEMPERATURE RISES BY AT MOST TEN PERCENT IN EACH.  JUST
C     BELOW THE PHOTOSPHERE OF A LOW-GRAVITY STAR THE RADIATIVE
C     GRADIENT CAN REACH SEVERAL (THE OPACITY CLIMBS STEEPLY
C     WITH T) WHILE THE THIN MATERIAL CONVECTS TOO WEAKLY TO
C     MATTER, AND A WHOLE-ZONE EULER STEP THEN OVERSHOOTS THE
C     OPACITY PEAK BY FACTORS OF TWO OR MORE - A CHAOTIC
C     AMPLIFIER THAT ONCE MADE THE FITTED SURFACE QUANTITIES
C     NOISE AND THE SURFACE NEWTON A COIN TOSS.
      DMUR=DMU
      DO 38 ISUB=1,200
      T1=G*XM/R3
C     THERMODYNAMIC QUANTITIES OF THE LAYER FROM THE IONIZATION
C     EQUILIBRIUM (HVB 1965, SEC. II)
      PG=P-ARAD*TX**4/3.
      IF (PG.LT.0.1*P) PG=0.1*P
      CALL THERME(PG,TX,XSU,ZMET,RHO,CPD,DELD,GRADA)
      CALL OPAC(TX,RHO**0.3333333,XSU,ZMET,CPS,D1,D2)
      GRR=C64*CPS*(XLS/XM)*(P/TX**4)
C     WHERE THE LAYER IS UNSTABLE, THE GRADIENT COMES FROM THE
C     BOEHM-VITENSE (1958) MIXING-LENGTH THEORY, WITH ALPHA (THE
C     RATIO OF MIXING LENGTH TO PRESSURE SCALE HEIGHT) FREE.
C     THE CUBIC IN XI = SQRT(GRAD - GRADAD + U**2),
C        (XI-U)**3 + (8U/9)(XI**2 - U**2 - W) = 0,
C     WITH W = GRADRAD - GRADAD AND
C     U = 12 SIGMA T**3 SQRT(8 HP/(GEE*DELTA))/(CP RHO**2 K L**2),
C     IS SOLVED BY BISECTION.
      GRAD=GRR
      IF (GRR.LE.GRADA) GO TO 34
      GEE=G*XM/R3**0.6666667
      HP=P/(RHO*GEE)
      EL=ALFA*HP
      UMLT=12.*SIG*TX**3*SQRT(8.*HP/(GEE*DELD))/(CPD*RHO*RHO*CPS
     1   *EL*EL)
      WMLT=GRR-GRADA
      X1B=UMLT
      X2B=SQRT(WMLT+UMLT*UMLT)
      DO 32 IB=1,45
      XMB=0.5*(X1B+X2B)
      FCB=(XMB-UMLT)**3+(8.*UMLT/9.)*(XMB*XMB-UMLT*UMLT-WMLT)
      IF (FCB.GT.0.) X2B=XMB
      IF (FCB.LE.0.) X1B=XMB
   32 CONTINUE
      GRAD=GRADA+XMB*XMB-UMLT*UMLT
   34 CONTINUE
C     HYDROSTATIC STEP (STAGED TO AVOID OVERFLOW OF R**4),
C     SHORTENED WHEN THE TEMPERATURE WOULD OUTRUN THE LIMIT
      DMUS=DMUR
      DP=T1*(DMUR/(12.566371*R3**0.3333333))
      DLP=LOG(1.D0+DP/P)
      IF (GRAD*DLP.GT.0.10D0 .AND. ISUB.LT.200) THEN
         FRS=0.10D0/(GRAD*DLP)
         IF (FRS.LT.1.D0) DMUS=DMUR*FRS
      END IF
      DP=T1*(DMUS/(12.566371*R3**0.3333333))
      PN=P+DP
      TX=TX*(PN/P)**GRAD
      P=PN
      R3=R3-DMUS/(4.1887902*RHO)
      R3MIN=0.001*RS**3
      IF (R3.LT.R3MIN) R3=R3MIN
      DMUR=DMUR-DMUS
      IF (DMUR.LE.1.D-12*DMU) GO TO 39
   38 CONTINUE
   39 CONTINUE
      XMU=XMUN
   40 CONTINUE
   45 CONTINUE
      RF=R3**0.3333333
      TF=TX
      QF=RHO**0.3333333
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE TTAU - THE BLANKETED RADIATIVE TEMPERATURE LAW OF
C     HENYEY, VARDYA + BODENHEIMER (1965), EQ. (10),
C        T**4 = (3/4)*TF**4*(TAU + 0.727 - 0.1406*EXP(-2.54*TAU))
C               + ZETA*(A - B*EXP(-30*TAU)),
C     AND ITS DERIVATIVE WITH RESPECT TO THE (EFFECTIVE) OPTICAL
C     DEPTH.  THE EXPONENTIALS ARE GUARDED AGAINST UNDERFLOW AND
C     THE FOURTH POWER OF THE TEMPERATURE IS KEPT ABOVE A SMALL
C     FLOOR.
C     ------------------------------------------------------------------
      SUBROUTINE TTAU(TAUP,TE4,ZETA,ABLK,BBLK,T4X,DT4)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      EX1=0.
      ARG=-2.54*TAUP
      IF (ARG.GT.-80.) EX1=EXP(ARG)
      EX2=0.
      ARG=-30.*TAUP
      IF (ARG.GT.-80.) EX2=EXP(ARG)
      T4X=0.75*TE4*(TAUP+0.727-0.1406*EX1)+ZETA*(ABLK-BBLK*EX2)
      IF (T4X.LT.0.05*TE4) T4X=0.05*TE4
      DT4=0.75*TE4*(1.+0.3571240*EX1)+30.*ZETA*BBLK*EX2
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE SAHA - IONIZATION EQUILIBRIUM AND THERMODYNAMICS
C     OF THE ENVELOPE MATERIAL, AFTER THE TREATMENT OF VARDYA
C     DESCRIBED IN HENYEY, VARDYA + BODENHEIMER (1965, AP. J.
C     142, 841, SEC. II).  HYDROGEN (H, H+), HELIUM (HE, HE+,
C     HE++), AND A SINGLE REPRESENTATIVE METAL (FIRST IONIZATION
C     7.5 EV, MEAN WEIGHT 24) SUPPLY THE ELECTRON PRESSURE.
C     MOLECULES, THE H- STATES OF THE FULL VARDYA TREATMENT, AND
C     THE TURBULENT PRESSURE OF HVB (WHICH PROVED CONTROVERSIAL)
C     ARE OMITTED.  RETURNED ARE THE DENSITY, THE SPECIFIC HEAT
C     AT CONSTANT PRESSURE, THE EXPANSION COEFFICIENT
C     DELTA = -DLNRHO/DLNT AT CONSTANT P, AND THE ADIABATIC
C     GRADIENT, THE LAST THREE BY DIFFERENCES OF THE EQUILIBRIUM
C     AT NEIGHBORING STATES.
C     ------------------------------------------------------------------
      SUBROUTINE SAHA(PG,TT,X,Z,RHO,CP,DELTA,GRADA)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      EPS=0.02
      CALL SAHA1(PG,TT,X,Z,RHO,H0)
      CALL SAHA1(PG,TT*(1.+EPS),X,Z,RH1,H1)
      DELTA=-(LOG(RH1)-LOG(RHO))/EPS
      IF (DELTA.LT.0.1) DELTA=0.1
      CP=(H1-H0)/(EPS*TT)
      GRADA=PG*DELTA/(TT*RHO*CP)
      IF (GRADA.LT.0.03) GRADA=0.03
      IF (GRADA.GT.0.42) GRADA=0.42
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE SAHA1 - ONE SOLUTION OF THE IONIZATION
C     EQUILIBRIUM AT GIVEN GAS PRESSURE AND TEMPERATURE (C.G.S.).
C     THE ELECTRON PRESSURE IS FOUND BY A DAMPED FIXED-POINT
C     ITERATION OF FIXED LENGTH, SO THAT THE MAPPING REMAINS
C     SMOOTH IN ITS ARGUMENTS (SEE THE REMARKS ON CONTINUITY IN
C     SEC. V OF THE 1964 PAPER).  THE SAHA FUNCTIONS ARE IN THE
C     PRESSURE FORM, PHI = 0.6665*(U1/U0)*T**2.5*EXP(-CHI/KT).
C     RETURNED ARE THE DENSITY AND THE SPECIFIC ENTHALPY
C     (TRANSLATION PLUS IONIZATION).
C     ------------------------------------------------------------------
      SUBROUTINE SAHA1(PG,TT,X,Z,RHO,HH)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      TC=TT
      PC=PG
      Y=1.-X-Z
      ANH=X/1.008
      ANHE=Y/4.003
      ANM=Z/24.
      RHE=ANHE/ANH
      RM=ANM/ANH
      T25=TC*TC*SQRT(TC)
      PH=0.
      ARG=-157800./TC
      IF (ARG.GT.-80.) PH=0.3333*T25*EXP(ARG)
      PB1=0.
      ARG=-285300./TC
      IF (ARG.GT.-80.) PB1=1.333*T25*EXP(ARG)
      PB2=0.
      ARG=-631500./TC
      IF (ARG.GT.-80.) PB2=0.3333*T25*EXP(ARG)
      PM=0.
      ARG=-87000./TC
      IF (ARG.GT.-80.) PM=0.6665*T25*EXP(ARG)
C     THE H2 DISSOCIATION CONSTANT KP = P(H)**2/P(H2) IN THE
C     PRESSURE FORM, FROM THE POLYNOMIAL FIT OF TSUJI (1973,
C     ASTRON. AP. 23, 411, TABLE 2) IN THETA = 5040/T.  VARDYA'S
C     ATMOSPHERE PROGRAM CARRIED THE MOLECULE, AND WITHOUT IT THE
C     ADIABAT OF A COOL GIANT IS BLIND TO DISSOCIATION AND THE
C     HAYASHI LINE COMES OUT WRONG.  THETA IS CAPPED AT 12 (THE
C     FIT'S COLD END); BELOW THAT THE HYDROGEN IS WHOLLY
C     MOLECULAR IN ANY CASE.
      TH=5040./TC
      IF (TH.GT.12.D0) TH=12.D0
      QL=12.533505D0+TH*(-4.9251644D0+TH*(0.056191273D0
     1   +TH*(-0.0032687661D0+TH*0.00026708111D0)))
      IF (QL.GT.30.D0) QL=30.D0
      PK=10.D0**QL
      IF (PK.LT.1.D-30) PK=1.D-30
C     OUTER FIXED POINT ON THE ELECTRON PRESSURE (FIXED LENGTH,
C     GEOMETRIC DAMPING, FOR SMOOTHNESS IN THE ARGUMENTS); THE
C     INNER LOOP SETTLES THE HYDROGEN-NUCLEUS PRESSURE BUDGET
C     B = P(H) + P(H+) + 2*P(H2), FROM WHICH THE ATOM PRESSURE
C     FOLLOWS BY THE CONJUGATE ROOT OF ITS QUADRATIC.
      PE=0.01*PC
      B=0.5*PC
      DO 20 IT=1,60
      FM=PM/(PM+PE)
      R1=MIN(PB1/PE,1.D15)
      R2=MIN(PB2/PE,1.D15)
      D=1.+R1+R1*R2
      Y1=R1/D
      Y2=R1*R2/D
      RAT=1.+PH/PE
      DO 15 IB=1,25
      P1=2.*B/(RAT+SQRT(RAT*RAT+8.*B/PK))
      PH2=P1*P1/PK
      PHP=P1*PH/PE
      PHE=RHE*B
      PMM=RM*B
      TOT=P1+PHP+PH2+PHE+PMM+PE
      B=B*(PC-PE)/MAX(TOT-PE,1.D-30)
   15 CONTINUE
      PEN=PHP+(Y1+2.*Y2)*PHE+FM*PMM
      IF (PEN.LT.1.D-25) PEN=1.D-25
      PE=SQRT(PE*PEN)
   20 CONTINUE
      P1=2.*B/(RAT+SQRT(RAT*RAT+8.*B/PK))
      PH2=P1*P1/PK
      PHP=P1*PH/PE
      PHE=RHE*B
      PMM=RM*B
C     MASS PER VOLUME FROM THE NUCLEUS BUDGETS (B COUNTS EVERY
C     HYDROGEN NUCLEUS ONCE, HOWEVER BOUND)
      RHO=(1.008D0*B+4.003D0*PHE+24.D0*PMM)/(8.25D7*TC)
      IF (RHO.LT.1.D-30) RHO=1.D-30
C     ENTHALPY PER GRAM - TRANSLATION (5/2 KT PER PARTICLE, ALL
C     SPECIES), THE ROTATION OF THE MOLECULE (KT PER H2),
C     IONIZATION, AND THE DISSOCIATION ENERGY 4.478 EV CARRIED BY
C     THE FREE ATOMS
      CMOL=1./(8.25D7*TC*RHO)
      HH=(2.5D0*PC+PH2)/RHO+9.648D11*CMOL*(PHP*13.60D0
     1   +PHE*(Y1*24.59D0+Y2*79.01D0)+FM*PMM*7.5D0
     2   -PH2*4.478D0)
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE STATE - EQUATION OF STATE OF THE INTERIOR.  THE
C     MODIFIED VARIABLE P = P**(1/4) AND THE DERIVATIVES FOR THE
C     JACOBIAN ARE FORMED FROM CENTERED DIFFERENCES OF THE
C     EVALUATOR STATEB, WHICH DISPATCHES BETWEEN THE SAUMON,
C     CHABRIER + VAN HORN (1995) TABLES AND THE BFGH (1965)
C     APPENDIX A FORM ACCORDING TO THE CARD-2 SELECTION AND THE
C     TABLE RANGE.  THE COMPOSITION ENTERS AS THE HYDROGEN MASS
C     FRACTION (FOR THE TABLES) AND AS THE MOLES PER GRAM OF IONS
C     AND OF FREE ELECTRONS (FOR THE BFGH FORM).
C     ------------------------------------------------------------------
      SUBROUTINE STATE(TT,QQ,X,ANUI,ANUE,PPX,DPTX,DPQX,EX,DETX,
     1   DEQX)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      DEL=0.02
      CALL STATEB(TT,QQ,X,ANUI,ANUE,P0,E0)
      CALL STATEB(TT*(1.+DEL),QQ,X,ANUI,ANUE,P1,E1)
      CALL STATEB(TT*(1.-DEL),QQ,X,ANUI,ANUE,P2,E2)
      CALL STATEB(TT,QQ*(1.+DEL),X,ANUI,ANUE,P3,E3)
      CALL STATEB(TT,QQ*(1.-DEL),X,ANUI,ANUE,P4,E4)
      PPX=SQRT(SQRT(P0))
      C=0.25*PPX/P0
      DPTX=C*(P1-P2)/(2.*DEL*TT)
      DPQX=C*(P3-P4)/(2.*DEL*QQ)
      EX=E0
      DETX=(E1-E2)/(2.*DEL*TT)
      DEQX=(E3-E4)/(2.*DEL*QQ)
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE STATEB - ONE EVALUATION OF PRESSURE AND INTERNAL
C     ENERGY, DISPATCHING BETWEEN THE SCVH TABLES AND THE BFGH
C     APPENDIX A FORM.  THE TABLES END AT LOG T = 7.06, SO ABOVE
C     LOG T = 7.02 THE BFGH FORM IS USED, BELOW 6.90 THE TABLES,
C     AND BETWEEN THE TWO THE RESULTS ARE JOINED BY A SMOOTHSTEP
C     WEIGHT THAT IS C1 IN TEMPERATURE.  (IN THE OVERLAP BOTH
C     DESCRIBE A NEARLY IDEAL FULLY IONIZED PLASMA AND AGREE TO
C     ABOUT A PER CENT.)  RADIATION IS INCLUDED ON BOTH BRANCHES.
C     ------------------------------------------------------------------
      SUBROUTINE STATEB(TT,QQ,X,ANUI,ANUE,P,E)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /EOSC/ IEOS,IOPC
      IF (IEOS.EQ.1) GO TO 20
      TL=LOG10(TT)
      W=(TL-6.90)/0.12
      IF (W.LT.0.) W=0.
      IF (W.GT.1.) W=1.
      W=W*W*(3.-2.*W)
C     THE TABLES ALSO END IN DENSITY (LOG P = 19, ABOUT LOG RHO
C     = 3.9 WHEN DEGENERATE) - THE CONTRACTING CORES OF SPENT
C     DWARFS DRIVE PAST THAT EDGE, WHERE THE INVERSION WOULD PIN
C     AT THE TABLE BOUNDARY AND THE PRESSURE WOULD LOSE ITS
C     DENSITY DEPENDENCE ENTIRELY.  A SECOND SMOOTHSTEP HANDS THE
C     HIGH-DENSITY SIDE TO THE BFGH FORM, WHICH CARRIES ARBITRARY
C     DEGENERACY.
      RL=3.D0*LOG10(QQ)
      WR=(RL-3.4D0)/0.4D0
      IF (WR.LT.0.) WR=0.
      IF (WR.GT.1.) WR=1.
      WR=WR*WR*(3.-2.*WR)
      W=1.D0-(1.D0-W)*(1.D0-WR)
      IF (W.GE.1.) GO TO 20
      CALL SCVLOW(TT,QQ,X,PS,ES)
      IF (W.LE.0.) GO TO 10
      CALL STATEV(TT,QQ,ANUI,ANUE,PB,EB)
      P=W*PB+(1.-W)*PS
      E=W*EB+(1.-W)*ES
      RETURN
   10 P=PS
      E=ES
      RETURN
   20 CALL STATEV(TT,QQ,ANUI,ANUE,P,E)
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE SCVLOW - THE TABLE SIDE OF STATEB, GUARDED AT
C     THE LOW-PRESSURE EDGE.  THE SCVH GRID HAS A FLOOR AT
C     LOG P = 4.0, AND WITH THE FITTING MASS AT DELS = 1.E-4 THE
C     TENUOUS OUTER ZONES OF A TIP GIANT FALL WELL BELOW IT -
C     WHERE THE (T,Q) INVERSION WOULD PIN AT THE BOUNDARY AND
C     EXTRAPOLATE CUBICS.  BELOW THE FLOOR THE H2-AWARE SAHA
C     EQUILIBRIUM SERVES, READ THE OTHER WAY ROUND (SUBROUTINE
C     SAHAPE), WITH A SMOOTH BLEND ACROSS LOG P = 4.0 TO 4.4 -
C     THE INTERIOR TWIN OF THE ENVELOPE'S OWN THERME BLEND.  AN
C     IDEAL-GAS ESTIMATE SKIPS THE SAHA WORK WHEREVER THE
C     PRESSURE IS SAFELY ON-TABLE.
C     ------------------------------------------------------------------
      SUBROUTINE SCVLOW(TT,QQ,X,P,E)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /STARP/ XM,XMI,ZMET,QHYD
      RHO=QQ**3
      PLEST=LOG10(RHO*8.25D7*TT)
      IF (PLEST.GT.5.0D0) THEN
         CALL SCVEV(TT,QQ,X,P,E)
         RETURN
      END IF
      CALL SAHAPE(TT,RHO,X,ZMET,PGS,PSA,ESA)
      PLS=LOG10(PGS)
      IF (PLS.LE.4.0D0) THEN
         P=PSA
         E=ESA
         RETURN
      END IF
      CALL SCVEV(TT,QQ,X,PS,ES)
      IF (PLS.GE.4.4D0) THEN
         P=PS
         E=ES
         RETURN
      END IF
      WS=(4.4D0-PLS)/0.4D0
      WS=WS*WS*(3.D0-2.D0*WS)
      P=WS*PSA+(1.D0-WS)*PS
      E=WS*ESA+(1.D0-WS)*ES
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE SAHAPE - THE SAHA EQUILIBRIUM READ THE OTHER WAY
C     ROUND: GIVEN THE TEMPERATURE AND DENSITY, THE GAS PRESSURE
C     IS FOUND BY A FIXED-LENGTH MULTIPLICATIVE ITERATION ON
C     SAHA1 (THE DENSITY IS NEARLY PROPORTIONAL TO THE PRESSURE -
C     THE MEAN WEIGHT SHIFTS THE SLOPE BY AT MOST THIRTY PERCENT
C     THROUGH THE IONIZATION AND DISSOCIATION ZONES - SO
C     PG <- PG*(RHO/RHO(PG)) CONVERGES GEOMETRICALLY), AND THE
C     INTERNAL ENERGY FOLLOWS FROM THE ENTHALPY.  RADIATION IS
C     ADDED EXPLICITLY, MATCHING THE OTHER BRANCHES OF STATEB.
C     THE FIXED LENGTH KEEPS THE MAPPING SMOOTH IN ITS ARGUMENTS,
C     AS THE CENTERED DIFFERENCES OF STATE REQUIRE.
C     ------------------------------------------------------------------
      SUBROUTINE SAHAPE(TT,RHO,X,Z,PG,P,E)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /CONST/ G,SIG,ARAD,RGAS,PI,C256,C4PS,C8PI
      PG=RHO*8.25D7*TT*0.8D0
      DO 10 IT=1,40
      CALL SAHA1(PG,TT,X,Z,RHC,HH)
      RAT=RHO/RHC
      IF (RAT.GT.10.D0) RAT=10.D0
      IF (RAT.LT.0.1D0) RAT=0.1D0
      PG=PG*RAT
   10 CONTINUE
      CALL SAHA1(PG,TT,X,Z,RHC,HH)
      PR=ARAD*TT**4/3.D0
      P=PG+PR
      E=HH-PG/RHC+3.D0*PR/RHO
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE STATEV - ONE EVALUATION OF PRESSURE AND INTERNAL
C     ENERGY PER GRAM AT GIVEN T AND Q (C.G.S.).  THE BFGH
C     FORMULAE ARE WRITTEN IN T7 = T/1.E7, SO THE CONSTANTS OF
C     THE APPENDIX TRANSCRIBE VERBATIM.
C     ------------------------------------------------------------------
      SUBROUTINE STATEV(TT,QQ,ANUI,ANUE,P,E)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /CONST/ G,SIG,ARAD,RGAS,PI,C256,C4PS,C8PI
      RHO=QQ**3
      T7=1.D-7*TT
C     DEGENERACY PARAMETER G (EQ. A3) AND CORRECTION H (EQ. A7)
      GDEG=3.945D-3*RHO*ANUE/T7**1.5
      HDEG=1./(1.+3.927D-5*GDEG*GDEG)
     1   +0.176777*GDEG/(1.+0.04885*GDEG)**0.3333333
C     RELATIVISTIC FACTOR K(X) (EQS. A9, A12)
      XREL=(1.0259D-6*RHO*ANUE)**0.3333333
      RK=0.0864+0.9136*SQRT(1.+0.7567*XREL*XREL)
      PG=RGAS*RHO*TT*(ANUI+ANUE*HDEG/RK)
      PR=ARAD*TT**4/3.
      P=PG+PR
      E=RGAS*TT*(1.5*ANUI+3.*ANUE*HDEG/(1.+RK))+3.*PR/RHO
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE SCVRD - READ THE SAUMON, CHABRIER + VAN HORN
C     (1995) HYDROGEN AND HELIUM TABLES (THE INTERPOLATED FORM,
C     FILES SCVH/H_TAB_I.DAT AND SCVH/HE_TAB_I.DAT - SEE
C     SCVH/README.MD FOR FORMAT AND PROVENANCE).  EACH ISOTHERM
C     BLOCK CARRIES LOG T AND ITS NUMBER OF PRESSURE POINTS, THEN
C     ONE ROW PER PRESSURE - LOG P, TWO CONCENTRATIONS, LOG RHO,
C     LOG S, LOG U, THE FOUR LOGARITHMIC DERIVATIVES OF RHO AND
C     S, AND THE ADIABATIC GRADIENT.  STORED ARE LOG RHO AND
C     LOG U WITH THEIR LOG-LOG SLOPES IN P AND T, THE SLOPES OF U
C     DERIVED AT EACH NODE FROM THE TABULATED RHO AND S
C     DERIVATIVES THROUGH  DU = T DS + (P/RHO**2) DRHO.  THE GRID
C     IS VERIFIED AGAINST THE PUBLISHED SPACING - LOG T FROM 2.10
C     IN STEPS OF 0.08, LOG P FROM 4.0 IN STEPS OF 0.2.
C     ------------------------------------------------------------------
      SUBROUTINE SCVRD
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /SCVT/ TLG(63),RLT(76,63,2),ULT(76,63,2),
     1   DRPT(76,63,2),DRTT(76,63,2),SUPT(76,63,2),SUTT(76,63,2),
     2   NPR(63,2),NT
      DO 60 IS=1,2
      IF (IS.EQ.2) GO TO 4
      OPEN (4,FILE='scvh/h_tab_i.dat',STATUS='OLD',ERR=2)
      GO TO 8
    2 OPEN (4,FILE='h_tab_i.dat',STATUS='OLD',ERR=6)
      GO TO 8
    4 OPEN (4,FILE='scvh/he_tab_i.dat',STATUS='OLD',ERR=5)
      GO TO 8
    5 OPEN (4,FILE='he_tab_i.dat',STATUS='OLD',ERR=6)
      GO TO 8
    6 WRITE (6,690)
      STOP 3
    8 CONTINUE
      I=0
   10 READ (4,*,END=50) TL,NPX
      NP=IDINT(NPX+0.5D0)
      I=I+1
      IF (I.GT.63 .OR. NP.GT.76 .OR. NP.LT.2) GO TO 45
      IF (ABS(TL-2.10D0-0.08D0*(I-1)).GT.1.D-3) GO TO 45
      TLG(I)=TL
      NPR(I,IS)=NP
      TX=10.D0**TL
      DO 20 K=1,NP
      READ (4,*,END=45) PL,C1,C2,RL,SL,UL,DRT,DRP,DST,DSP,GAD
      IF (ABS(PL-4.0D0-0.2D0*(K-1)).GT.1.D-3) GO TO 45
      PX=10.D0**PL
      SX=10.D0**SL
      RX=10.D0**RL
      UX=10.D0**UL
      RLT(K,I,IS)=RL
      ULT(K,I,IS)=UL
      DRPT(K,I,IS)=DRP
      DRTT(K,I,IS)=DRT
      SUPT(K,I,IS)=(TX*SX*DSP+PX/RX*DRP)/UX
      SUTT(K,I,IS)=(TX*SX*DST+PX/RX*DRT)/UX
   20 CONTINUE
      GO TO 10
   45 WRITE (6,691)
      STOP 3
   50 CLOSE (4)
      IF (IS.EQ.1) NT=I
      IF (I.LT.2) GO TO 45
      IF (IS.EQ.2 .AND. I.NE.NT) GO TO 45
   60 CONTINUE
      WRITE (6,692) NT,TLG(1),TLG(NT)
      RETURN
  690 FORMAT ('0','SCVH TABLES NOT FOUND (SCVH/H_TAB_I.DAT)')
  691 FORMAT ('0','SCVH TABLE GRID UNEXPECTED')
  692 FORMAT (' SCVH TABLES READ -',I4,' ISOTHERMS, LOG T =',
     1   F5.2,' TO',F5.2)
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE HERM1 - CUBIC HERMITE INTERPOLATION ON ONE
C     SEGMENT OF WIDTH H, GIVEN END VALUES AND END SLOPES,
C     EVALUATED AT OFFSET U FROM THE LEFT END.  OUTSIDE THE
C     SEGMENT THE END VALUE CONTINUES LINEARLY WITH THE END
C     SLOPE, WHICH KEEPS EXTRAPOLATION BEYOND A TABLE ROW TAME.
C     RETURNS THE VALUE AND THE SLOPE.
C     ------------------------------------------------------------------
      SUBROUTINE HERM1(H,Y1,Y2,S1,S2,U,Y,DY)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      IF (U.GE.0.) GO TO 10
      Y=Y1+S1*U
      DY=S1
      RETURN
   10 IF (U.LE.H) GO TO 20
      Y=Y2+S2*(U-H)
      DY=S2
      RETURN
   20 TB=U/H
      T2=TB*TB
      T3=T2*TB
      Y=(2.*T3-3.*T2+1.)*Y1+(T3-2.*T2+TB)*H*S1
     1   +(-2.*T3+3.*T2)*Y2+(T3-T2)*H*S2
      DY=(6.*T2-6.*TB)*(Y1-Y2)/H+(3.*T2-4.*TB+1.)*S1
     1   +(3.*T2-2.*TB)*S2
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE SCVI1 - ONE C1 INTERPOLATION IN THE SCVH TABLE
C     OF SPECIES IS (1 HYDROGEN, 2 HELIUM) AT (LOG T, LOG P).
C     ALONG EACH OF THE TWO BRACKETING ISOTHERMS, LOG RHO AND
C     LOG U ARE INTERPOLATED BY CUBIC HERMITE SEGMENTS WHOSE END
C     SLOPES ARE THE TABULATED LOGARITHMIC DERIVATIVES, SO THE
C     SURFACE HONORS THE PUBLISHED DERIVATIVES EXACTLY AND IS C1
C     IN LOG P; THE TWO ISOTHERM RESULTS ARE THEN JOINED BY A
C     HERMITE STEP IN LOG T ON THE TABULATED T-SLOPES, GIVING C1
C     IN TEMPERATURE AS THE NEWTON SCHEME REQUIRES (HFG 1964,
C     SEC. V AND FIG. 3).  RETURNED ARE LOG RHO, ITS SLOPE IN
C     LOG P, AND LOG U.
C     ------------------------------------------------------------------
      SUBROUTINE SCVI1(IS,TL,PL,RLV,DRPV,ULV,DRTV,SUTV)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /SCVT/ TLG(63),RLT(76,63,2),ULT(76,63,2),
     1   DRPT(76,63,2),DRTT(76,63,2),SUPT(76,63,2),SUTT(76,63,2),
     2   NPR(63,2),NT
      DIMENSION RLI(2),DRPI(2),DRTI(2),DDRP(2),ULI(2),SUTI(2)
      I=IDINT((TL-2.10D0)/0.08D0)+1
      IF (I.LT.1) I=1
      IF (I.GT.NT-1) I=NT-1
      DO 30 M=1,2
      IR=I+M-1
      NP=NPR(IR,IS)
      K=IDINT((PL-4.0D0)/0.2D0)+1
      IF (K.LT.1) K=1
      IF (K.GT.NP-1) K=NP-1
      U=PL-4.0D0-0.2D0*(K-1)
      CALL HERM1(0.2D0,RLT(K,IR,IS),RLT(K+1,IR,IS),
     1   DRPT(K,IR,IS),DRPT(K+1,IR,IS),U,RLI(M),DRPI(M))
      CALL HERM1(0.2D0,ULT(K,IR,IS),ULT(K+1,IR,IS),
     1   SUPT(K,IR,IS),SUPT(K+1,IR,IS),U,ULI(M),DUM)
      FR=U/0.2D0
      IF (FR.LT.0.) FR=0.
      IF (FR.GT.1.) FR=1.
      DRTI(M)=(1.-FR)*DRTT(K,IR,IS)+FR*DRTT(K+1,IR,IS)
      DDRP(M)=(DRTT(K+1,IR,IS)-DRTT(K,IR,IS))/0.2D0
      SUTI(M)=(1.-FR)*SUTT(K,IR,IS)+FR*SUTT(K+1,IR,IS)
   30 CONTINUE
      UT=TL-TLG(I)
      CALL HERM1(0.08D0,RLI(1),RLI(2),DRTI(1),DRTI(2),UT,RLV,DUM)
      CALL HERM1(0.08D0,ULI(1),ULI(2),SUTI(1),SUTI(2),UT,ULV,DUM)
C     THE LOG-P SLOPE OF THE T-HERMITE - THE SAME BASIS APPLIED
C     TO THE P-DERIVATIVES OF ITS FOUR COEFFICIENTS
      CALL HERM1(0.08D0,DRPI(1),DRPI(2),DDRP(1),DDRP(2),UT,DRPV,
     1   DUM)
C     THE T-SLOPES OF RHO AND U AT THE POINT, LINEAR ACROSS THE
C     ISOTHERM PAIR - USED BY THE ENVELOPE THERMODYNAMICS
      FT=UT/0.08D0
      IF (FT.LT.0.) FT=0.
      IF (FT.GT.1.) FT=1.
      DRTV=(1.-FT)*DRTI(1)+FT*DRTI(2)
      SUTV=(1.-FT)*SUTI(1)+FT*SUTI(2)
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE SCVEV - ONE EVALUATION OF PRESSURE AND INTERNAL
C     ENERGY FROM THE SCVH TABLES AT GIVEN T AND Q.  THE TABLES
C     ARE INDEXED BY (T, P), SO THE GAS PRESSURE IS FOUND BY A
C     NEWTON ITERATION ON LOG P AT FIXED T UNTIL THE
C     ADDITIVE-VOLUME MIXTURE DENSITY,
C          1/RHO = X/RHO(H) + (1-X)/RHO(HE),
C     MATCHES Q**3 (LB93 SEC. 2; THE HELIUM TABLE CARRIES THE
C     HELIUM PLUS METAL MASS, AND THE ENTROPY OF MIXING IS NOT
C     NEEDED HERE - THE INTERIOR CONVECTION CRITERION USES THE
C     RADIATIVE GRADIENT AGAINST 0.40 AS BEFORE).  THE ITERATION
C     IS CONVERGED TO 1.E-11 SO THAT THE CENTERED DIFFERENCES
C     TAKEN BY STATE REMAIN SMOOTH.  RADIATION IS ADDED
C     EXPLICITLY, MATCHING THE BFGH BRANCH.
C     ------------------------------------------------------------------
      SUBROUTINE SCVEV(TT,QQ,X,P,E)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /CONST/ G,SIG,ARAD,RGAS,PI,C256,C4PS,C8PI
      RHO=QQ**3
      TL=LOG10(TT)
      RL0=3.D0*LOG10(QQ)
      PL=LOG10(RHO*8.25D7*TT)
      IF (PL.LT.4.0D0) PL=4.0D0
      IF (PL.GT.19.0D0) PL=19.0D0
      DO 10 IT=1,30
      CALL SCVI1(1,TL,PL,RLH,DRH,ULH,DT1,DT2)
      CALL SCVI1(2,TL,PL,RLE,DRE,ULE,DT3,DT4)
      RHH=10.D0**RLH
      RHE=10.D0**RLE
      RM=1.D0/(X/RHH+(1.D0-X)/RHE)
      SLP=RM*(X*DRH/RHH+(1.D0-X)*DRE/RHE)
      IF (SLP.LT.0.05D0) SLP=0.05D0
      D=(RL0-LOG10(RM))/SLP
      IF (D.GT.1.D0) D=1.D0
      IF (D.LT.-1.D0) D=-1.D0
      PL=PL+D
      IF (PL.LT.3.5D0) PL=3.5D0
      IF (PL.GT.19.5D0) PL=19.5D0
      IF (ABS(D).LT.1.D-11) GO TO 20
   10 CONTINUE
   20 CALL SCVI1(1,TL,PL,RLH,DRH,ULH,DT1,DT2)
      CALL SCVI1(2,TL,PL,RLE,DRE,ULE,DT3,DT4)
      PR=ARAD*TT**4/3.D0
      P=10.D0**PL+PR
      E=X*10.D0**ULH+(1.D0-X)*10.D0**ULE+3.D0*PR/RHO
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE SCVENV - ENVELOPE THERMODYNAMICS FROM THE SCVH
C     TABLES AT GIVEN GAS PRESSURE AND TEMPERATURE (THE TABLES
C     ARE INDEXED BY (T, P), SO NO INVERSION IS NEEDED HERE).
C     RETURNED ARE THE MIXTURE DENSITY BY ADDITIVE VOLUMES, THE
C     SPECIFIC HEAT AT CONSTANT PRESSURE, THE EXPANSION
C     COEFFICIENT DELTA = -DLNRHO/DLNT AT CONSTANT P, AND THE
C     ADIABATIC GRADIENT FROM THE THERMODYNAMIC IDENTITY
C        GRAD(AD) = P*DELTA/(T*RHO*CP),
C     WITH  CP = SUM OF W(I)*(U(I)*DLNU/DLNT - (P/RHO(I))*
C     DLNRHO/DLNT)/T  OVER THE TWO SPECIES - THE MIXTURE-CORRECT
C     ROUTE, SINCE GRAD(AD) ITSELF DOES NOT MASS-WEIGHT.  THIS
C     REPLACES THE SAHA EQUILIBRIUM (WHICH HAS NO MOLECULES) FOR
C     THE CASE-B ATMOSPHERE OF LB93 - THE SCVH TABLES CARRY H2,
C     SO THE ENVELOPE FOLLOWS THE TRUE DISSOCIATION-DEPRESSED
C     ADIABAT IN COOL ATMOSPHERES.
C     ------------------------------------------------------------------
      SUBROUTINE SCVENV(PG,TT,X,RHO,CP,DELTA,GRADA)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      TL=LOG10(TT)
      PGX=PG
      IF (PGX.LT.1.D-10) PGX=1.D-10
      PL=LOG10(PGX)
      CALL SCVI1(1,TL,PL,RLH,DRPH,ULH,DRTH,SUTH)
      CALL SCVI1(2,TL,PL,RLE,DRPE,ULE,DRTE,SUTE)
      RHH=10.D0**RLH
      RHE=10.D0**RLE
      UH=10.D0**ULH
      UE=10.D0**ULE
      RHO=1.D0/(X/RHH+(1.D0-X)/RHE)
      DELTA=-RHO*(X*DRTH/RHH+(1.D0-X)*DRTE/RHE)
      IF (DELTA.LT.0.05D0) DELTA=0.05D0
      CPH=(UH*SUTH-PGX/RHH*DRTH)/TT
      CPE=(UE*SUTE-PGX/RHE*DRTE)/TT
      CP=X*CPH+(1.D0-X)*CPE
      IF (CP.LT.1.D7) CP=1.D7
      GRADA=PGX*DELTA/(TT*RHO*CP)
      IF (GRADA.LT.0.03D0) GRADA=0.03D0
      IF (GRADA.GT.0.45D0) GRADA=0.45D0
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE THERME - ENVELOPE THERMODYNAMICS DISPATCHER.
C     THE SCVH TABLES WHEN THEY ARE THE SELECTED EQUATION OF
C     STATE (THE LB93 CASE-B PHYSICS), THE SAHA EQUILIBRIUM ON
C     THE LEGACY PATH.
C     THE SCVH PRESSURE GRID HAS A FLOOR AT LOG P = 4.0, AND THE
C     PHOTOSPHERE OF A GIANT (LOW GRAVITY, THE BLUEWARD CROSSING
C     OF AN ENVELOPE NEARING EXHAUSTION) FALLS WELL BELOW IT -
C     THERE THE HERMITE SEGMENTS WOULD BE EXTRAPOLATED MANY
C     WIDTHS BEYOND THE EDGE, WHERE A CUBIC IS NOT EVEN
C     MONOTONE, AND THE NEWTON SCHEME INHERITS THE WRECKAGE
C     THROUGH THE SURFACE FIT.  BELOW THE FLOOR THE SAHA
C     EQUILIBRIUM SERVES (AT THESE PRESSURES THE GAS IS NEARLY
C     IDEAL AND MOLECULES ARE MINOR AT THE TEMPERATURES THAT
C     REACH SO LOW A PRESSURE), WITH A SMOOTH BLEND ACROSS
C     LOG P = 4.0 TO 4.4 - THE TWIN OF THE HIGH-DENSITY BLEND
C     THAT GUARDS THE OTHER EDGE OF THE TABLES IN STATEB.
C     ------------------------------------------------------------------
      SUBROUTINE THERME(PG,TT,X,Z,RHO,CP,DELTA,GRADA)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /EOSC/ IEOS,IOPC
      IF (IEOS.EQ.0) THEN
         PGX=MAX(PG,1.D-10)
         PL=LOG10(PGX)
C        THE SAHA WEIGHT RISES AS THE PRESSURE FALLS THROUGH THE
C        TABLE FLOOR.  THE SAHA EQUILIBRIUM CARRIES THE H2
C        MOLECULE (TSUJI 1973 DISSOCIATION CONSTANT, AS VARDYA'S
C        PROGRAM DID), SO IT SERVES AT EVERY TEMPERATURE THE LOW
C        PRESSURES REACH - AN EARLIER TEMPERATURE GATE THAT MIXED
C        THE TWO TREATMENTS ACROSS 3500-4500 K PUT THE SEAM
C        EXACTLY WHERE GIANT-TIP PHOTOSPHERES LIVE, AND THE
C        BRANCH DISAGREEMENT WIGGLED THE ENVELOPE PHYSICS AT
C        TEFF ~ 3700 K INTO A REPRODUCIBLE CONVERGENCE WALL.
         WP=(4.4D0-PL)/0.4D0
         IF (WP.LT.0.) WP=0.
         IF (WP.GT.1.) WP=1.
         WP=WP*WP*(3.D0-2.D0*WP)
         W=WP
         IF (W.LE.0.) THEN
            CALL SCVENV(PG,TT,X,RHO,CP,DELTA,GRADA)
         ELSE IF (W.GE.1.) THEN
            CALL SAHA(PG,TT,X,Z,RHO,CP,DELTA,GRADA)
         ELSE
            CALL SCVENV(PG,TT,X,RHS,CPS,DLS,GAS)
            CALL SAHA(PG,TT,X,Z,RHA,CPA2,DLA,GAA)
            RHO=EXP((1.D0-W)*LOG(RHS)+W*LOG(RHA))
            CP=EXP((1.D0-W)*LOG(CPS)+W*LOG(CPA2))
            DELTA=(1.D0-W)*DLS+W*DLA
            GRADA=(1.D0-W)*GAS+W*GAA
         END IF
      ELSE
         CALL SAHA(PG,TT,X,Z,RHO,CP,DELTA,GRADA)
      END IF
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE AJRV - THE LOW-TEMPERATURE ROSSELAND MEAN OPACITY
C     OF ALEXANDER, JOHNSON + RYPMA (1983, AP. J. 272, 773),
C     THEIR TABLE 2 MASTER GRID FOR THE CAMERON-PINE SOLAR
C     MIXTURE (X = 0.71, Y = 0.27, Z = 0.02), WHICH INCLUDES THE
C     MOLECULAR BANDS (H2O, TIO, CO, CN, ...) AND THE SILICATE
C     AND IRON GRAINS BELOW ABOUT 1600 K.  THE GRID RUNS FROM
C     LOG T = 2.80 TO 4.00 (NONUNIFORMLY - 0.05 STEPS TO 3.70,
C     THEN 0.10) OVER LOG RHO = -18 TO -2, AND IS RAGGED; ABSENT
C     CELLS CARRY THE SENTINEL 99.  INTERPOLATION IS CUBIC
C     HERMITE WITH CENTERED-DIFFERENCE SLOPES ALONG EACH ROW AND
C     ACROSS ROWS, C1 IN BOTH VARIABLES AS THE NEWTON SCHEME
C     REQUIRES; BEYOND THE DEFINED CELLS THE EDGE SEGMENT
C     CONTINUES LINEARLY.  RETURNED IS LOG10 KAPPA.
C     ------------------------------------------------------------------
      SUBROUTINE AJRV(TL,RL,CKL)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /AJRT/ TG(22),AK(17,22)
      DIMENSION VR(4),IOK(4)
C     BRACKETING ROW - THE ROW GRID IS NONUNIFORM, SO SEARCH
      J=1
      DO 10 JJ=2,21
      IF (TL.GE.TG(JJ)) J=JJ
   10 CONTINUE
C     EVALUATE ROWS J-1, J, J+1, J+2 AT RL WHERE DEFINED
      DO 20 M=1,4
      JR=J+M-2
      IOK(M)=0
      VR(M)=0.
      IF (JR.LT.1 .OR. JR.GT.22) GO TO 20
      CALL AJROW(JR,RL,VR(M),IOK(M))
   20 CONTINUE
C     T-SLOPES AT ROWS J AND J+1, MONOTONE-LIMITED (FRITSCH-
C     CARLSON) ON THE NONUNIFORM ROW GRID
      H=TG(J+1)-TG(J)
      DC=(VR(3)-VR(2))/H
      S1=DC
      IF (IOK(1).EQ.1) THEN
         DL=(VR(2)-VR(1))/(TG(J)-TG(J-1))
         S1=0.
         IF (DL*DC.GT.0.) THEN
            S1=0.5D0*(DL+DC)
            SL3=3.D0*MIN(ABS(DL),ABS(DC))
            IF (ABS(S1).GT.SL3) S1=SIGN(SL3,S1)
         END IF
      END IF
      S2=DC
      IF (IOK(4).EQ.1) THEN
         DR=(VR(4)-VR(3))/(TG(J+2)-TG(J+1))
         S2=0.
         IF (DC*DR.GT.0.) THEN
            S2=0.5D0*(DC+DR)
            SL3=3.D0*MIN(ABS(DC),ABS(DR))
            IF (ABS(S2).GT.SL3) S2=SIGN(SL3,S2)
         END IF
      END IF
      CALL HERM1(H,VR(2),VR(3),S1,S2,TL-TG(J),CKL,DUM)
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE AJROW - ONE ROW OF THE AJR TABLE EVALUATED AT
C     LOG RHO BY CUBIC HERMITE WITH CENTERED-DIFFERENCE SLOPES
C     OVER THE DEFINED CELLS (UNIT COLUMN SPACING, LOG RHO = -18
C     AT COLUMN 1).  OUTSIDE THE DEFINED RANGE THE EDGE SEGMENT
C     CONTINUES LINEARLY.  IOK = 0 IF THE ROW HAS FEWER THAN TWO
C     DEFINED CELLS.
C     ------------------------------------------------------------------
      SUBROUTINE AJROW(JR,RL,V,IOK)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /AJRT/ TG(22),AK(17,22)
      IOK=0
      K1=0
      K2=0
      DO 10 K=1,17
      IF (AK(K,JR).GT.50.) GO TO 10
      IF (K1.EQ.0) K1=K
      K2=K
   10 CONTINUE
      IF (K2.LE.K1) RETURN
      IOK=1
C     SEGMENT SELECTION, CLAMPED TO THE DEFINED CELLS
      XK=RL+19.D0
      K=IDINT(XK)
      IF (K.LT.K1) K=K1
      IF (K.GT.K2-1) K=K2-1
C     MONOTONE (FRITSCH-CARLSON) SLOPES AT THE SEGMENT ENDS -
C     THE GRAIN-CONDENSATION CELLS JUMP BY DECADES BETWEEN
C     NEIGHBORS, AND AN UNLIMITED CUBIC OSCILLATES THERE, WHICH
C     THE NEWTON PROCESS CANNOT ABIDE
      DC=AK(K+1,JR)-AK(K,JR)
      S1=DC
      IF (K.GT.K1) THEN
         DL=AK(K,JR)-AK(K-1,JR)
         S1=0.
         IF (DL*DC.GT.0.) THEN
            S1=0.5D0*(DL+DC)
            SL3=3.D0*MIN(ABS(DL),ABS(DC))
            IF (ABS(S1).GT.SL3) S1=SIGN(SL3,S1)
         END IF
      END IF
      S2=DC
      IF (K.LT.K2-1) THEN
         DR=AK(K+2,JR)-AK(K+1,JR)
         S2=0.
         IF (DC*DR.GT.0.) THEN
            S2=0.5D0*(DC+DR)
            SL3=3.D0*MIN(ABS(DC),ABS(DR))
            IF (ABS(S2).GT.SL3) S2=SIGN(SL3,S2)
         END IF
      END IF
      CALL HERM1(1.D0,AK(K,JR),AK(K+1,JR),S1,S2,XK-K,V,DUM)
      RETURN
      END
