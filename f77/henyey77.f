C     ------------------------------------------------------------------
C     SUBROUTINE OPAC - OPACITY AND ITS DERIVATIVES.  THE INTERIOR
C     ABSORPTION IS THE INTERPOLATION FORMULA OF APPENDIX B OF
C     BODENHEIMER, FORBES, GOULD + HENYEY (1965), FITTED TO THE
C     KELLER-MEYEROTT TABLE WITH CONSTANTS MODERNIZED TO COX AND
C     EILERS - HYDROGEN (B1), HELIUM (B2), HEAVY ELEMENTS WITH
C     THE GUILLOTINE BUILT IN (B3), ELECTRON SCATTERING (B4),
C     COMBINED BY THE PUBLISHED MIXING RULE (B5), WITH MESTEL
C     CONDUCTION (B6) JOINED RECIPROCALLY (B7).  BELOW ABOUT
C     1.E4 K AN H-MINUS TERM STANDS IN FOR THE VARDYA ATMOSPHERIC
C     OPACITY TABLE OF THE PRODUCTION CODE, JOINED HARMONICALLY
C     SO THAT KAPPA AND ITS DERIVATIVES REMAIN CONTINUOUS (SEC. V
C     AND FIG. 3 OF THE 1964 PAPER).  DERIVATIVES FOR THE
C     JACOBIAN ARE CENTERED DIFFERENCES OF THE EVALUATOR OPACV.
C     ------------------------------------------------------------------
      SUBROUTINE OPAC(TT,QQ,X,Z,CAP,DCT,DCQ)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      DEL=0.02
      CALL OPACV(TT,QQ,X,Z,C0)
      CALL OPACV(TT*(1.+DEL),QQ,X,Z,C1)
      CALL OPACV(TT*(1.-DEL),QQ,X,Z,C2)
      CALL OPACV(TT,QQ*(1.+DEL),X,Z,C3)
      CALL OPACV(TT,QQ*(1.-DEL),X,Z,C4)
      CAP=C0
      DCT=(C1-C2)/(2.*DEL*TT)
      DCQ=(C3-C4)/(2.*DEL*QQ)
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE OPACV - ONE EVALUATION OF THE OPACITY (C.G.S.).
C     THE BFGH FORMULAE ARE WRITTEN IN T7 = T/1.E7, SO THE
C     CONSTANTS OF THE APPENDIX TRANSCRIBE VERBATIM.
C     ------------------------------------------------------------------
      SUBROUTINE OPACV(TT,QQ,X,Z,CAP)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /EOSC/ IEOS,IOPC
      RHO=QQ**3
      T7=1.D-7*TT
      IF (IOPC.EQ.0) GO TO 10
C     LEGACY STACK - THE BFGH INTERIOR FORMULA JOINED
C     HARMONICALLY TO THE H-MINUS STAND-IN, AS BEFORE
      CALL BFGOP(T7,RHO,X,Z,CKI)
      CHMLG=-70.48+LOG(50.*Z)+0.5*LOG(RHO)+9.*LOG(TT)
      IF (CHMLG.LT.-80.) CHMLG=-80.
      RCHM=0.
      IF (CHMLG.LT.85.) RCHM=EXP(-CHMLG)
      CAP=1./(RCHM+1./CKI)
      RETURN
C     THE PHASE-4 STACK.  BELOW 1.E4 K THE ALEXANDER, JOHNSON +
C     RYPMA (1983) MOLECULE-AND-GRAIN TABLE, SCALED FOR
C     HELIUM-RICH MATERIAL BY LBA97 EQ. (2.1),
C        KAPPA(HE-RICH) = KAPPA * (1 - (0.7 - X)/2).
C     ABOVE 1.E5 K THE BFGH INTERIOR FORMULA (THE H-MINUS
C     STAND-IN IS RETIRED - ITS T**9 FIT IS UNPHYSICAL PAST ITS
C     3000-6000 K RANGE).  BETWEEN THE TWO, WHERE NEITHER SOURCE
C     IS TRUSTWORTHY, LOG KAPPA IS BRIDGED IN LOG T BY A CUBIC
C     HERMITE WHOSE END SLOPES MATCH THE ADJOINING BRANCHES - THE
C     TREATMENT OF HENYEY, VARDYA + BODENHEIMER (1965), WHO
C     INTERPOLATED IN T BETWEEN THEIR ATMOSPHERIC TABLE AND THE
C     INTERIOR OPACITY FOR EXACTLY THIS REASON.
   10 TL=LOG10(TT)
      RL=3.D0*LOG10(QQ)
      HES=1.D0-(0.70D0-X)/2.D0
      IF (HES.LT.0.5D0) HES=0.5D0
      IF (HES.GT.1.15D0) HES=1.15D0
      IF (TL.GE.5.0D0) GO TO 20
      IF (TL.GE.4.0D0) GO TO 30
      CALL AJRV(TL,RL,CKL)
      CAPR=10.D0**CKL*HES
      GO TO 40
C     THE HIGH-TEMPERATURE RADIATIVE OPACITY IS THE KING IVA
C     TABLE OF COX + TABOR (1976) - LB93'S NAMED SOURCE - AS THE
C     ABSOLUTE ANCHOR, WITH THE BFGH APPENDIX B FORMULA SUPPLYING
C     ONLY THE COMPOSITION SCALING ABOUT THE KING MIXTURE
C     (X = 0.70, Z = 0.02).
   20 CALL KIVV(TL,RL,CKL)
      CALL BFGRAD(T7,RHO,X,Z,CBA)
      CALL BFGRAD(T7,RHO,0.70D0,0.02D0,CBK)
      CAPR=10.D0**CKL*(CBA/CBK)
      GO TO 40
   30 CALL AJRV(4.00D0,RL,Y1)
      CALL AJRV(3.96D0,RL,Y0)
      S1=(Y1-Y0)/0.04D0
      Y1=Y1+LOG10(HES)
      CALL KIVV(5.00D0,RL,C5A)
      CALL KIVV(5.04D0,RL,C5B)
      CALL BFGRAD(1.0D-2,RHO,X,Z,CBA)
      CALL BFGRAD(1.0D-2,RHO,0.70D0,0.02D0,CBK)
      Y2=C5A+LOG10(CBA/CBK)
      S2=(C5B-C5A)/0.04D0
      CALL HERM1(1.D0,Y1,Y2,S1,S2,TL-4.0D0,YB,DUM)
      CAPR=10.D0**YB
C     ELECTRON CONDUCTION FROM THE HUBBARD-LAMPE (1969) TABLES,
C     JOINED RECIPROCALLY (THEIR EQ. 3).  WHERE CONDUCTION IS
C     IRRELEVANT THE TABLE EXTENSION MAKES KAPPA(COND) ENORMOUS
C     AND THE JOIN LEAVES THE RADIATIVE VALUE UNTOUCHED.
   40 CALL HLCV(TL,RL,X,CKC)
      CAP=1.D0/(1.D0/CAPR+1.D0/CKC)
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE BFGOP - THE BFGH (1965) APPENDIX B INTERIOR
C     OPACITY (RADIATIVE FORMULA B1-B5 WITH MESTEL CONDUCTION
C     B6-B7), WITHOUT THE H-MINUS TERM.  T7 = T/1.E7.  THIS FORM
C     SERVES THE LEGACY PATH; THE PHASE-4 STACK TAKES THE
C     RADIATIVE PART FROM BFGRAD AND THE CONDUCTION FROM THE
C     HUBBARD-LAMPE TABLES.
C     ------------------------------------------------------------------
      SUBROUTINE BFGOP(T7,RHO,X,Z,CKI)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      CALL BFGRAD(T7,RHO,X,Z,CKR)
C     B6 - CONDUCTION (MESTEL, VIA HASELGROVE + HOYLE)
      OPX=1.+X
      ARG=0.004364*OPX*RHO/T7**1.5
      CKC=301.8/(T7*(1.+ARG**1.6666667))
C     B7 - THE RECIPROCAL JOIN
      CKI=1./(1./CKR+1./CKC)
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE BFGRAD - THE RADIATIVE PART ALONE OF THE BFGH
C     (1965) APPENDIX B FORMULA (B1-B5).  T7 = T/1.E7.
C     ------------------------------------------------------------------
      SUBROUTINE BFGRAD(T7,RHO,X,Z,CKR)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      Y=1.-X-Z
      OPX=1.+X
      T72=T7*T7
C     B1 - HYDROGEN
      CK1=6.48D-3*OPX*X*RHO/T7**4.25
C     B2 - HELIUM
      CK2=186.*RHO*OPX*Y*(1.05D-3/(T72*T7*(10.*T7+1.))
     1   +(2.-Y)/(0.15+T7*(300.*T7-7.))**4)
C     B3 - HEAVY ELEMENTS, GUILLOTINE INCLUDED
      RX=RHO*OPX
      B3A=0.455*SQRT(RX)+1.
      B3B=5.38*T72/RX+1.
      B3C=1.34D5*T72*T72*T7/RX+1.
      B3D=1.44*T72+1./(10.*T7)**1.5
      CK3=4.38D3*Z/SQRT(B3A*B3B*B3C*B3D)
C     B4 - ELECTRON SCATTERING
      CK4=0.195*OPX
C     B5 - THE PUBLISHED COMBINATION
      SUM=CK1+CK2+CK3+CK4
      CKR=((CK1+CK2)*(CK3+CK4)+CK3*CK4)/SUM+SUM
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE MHERM - MONOTONE-LIMITED (FRITSCH-CARLSON)
C     HERMITE EVALUATION OVER ND GATHERED POINTS WITH GENERALLY
C     NONUNIFORM ABSCISSAE, CONTINUING LINEARLY BEYOND THE ENDS.
C     ------------------------------------------------------------------
      SUBROUTINE MHERM(ND,XD,YD,U,V)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      DIMENSION XD(ND),YD(ND)
      K=1
      DO 10 KK=2,ND-1
      IF (U.GE.XD(KK)) K=KK
   10 CONTINUE
      H=XD(K+1)-XD(K)
      DC=(YD(K+1)-YD(K))/H
      S1=DC
      IF (K.GT.1) THEN
         DL=(YD(K)-YD(K-1))/(XD(K)-XD(K-1))
         S1=0.
         IF (DL*DC.GT.0.) THEN
            S1=0.5D0*(DL+DC)
            SL3=3.D0*MIN(ABS(DL),ABS(DC))
            IF (ABS(S1).GT.SL3) S1=SIGN(SL3,S1)
         END IF
      END IF
      S2=DC
      IF (K.LT.ND-1) THEN
         DR=(YD(K+2)-YD(K+1))/(XD(K+2)-XD(K+1))
         S2=0.
         IF (DC*DR.GT.0.) THEN
            S2=0.5D0*(DC+DR)
            SL3=3.D0*MIN(ABS(DC),ABS(DR))
            IF (ABS(S2).GT.SL3) S2=SIGN(SL3,S2)
         END IF
      END IF
      CALL HERM1(H,YD(K),YD(K+1),S1,S2,U-XD(K),V,DUM)
      RETURN
      END
