   30 CONTINUE
      IF (IOK(2).EQ.1 .AND. IOK(3).EQ.1) GO TO 40
      CKL=0.
      IF (IOK(3).EQ.1) CKL=VR(3)
      IF (IOK(2).EQ.1) CKL=VR(2)
      RETURN
   40 H=TGK(J+1)-TGK(J)
      DC=(VR(3)-VR(2))/H
      S1=DC
      IF (IOK(1).EQ.1) THEN
         DL=(VR(2)-VR(1))/(TGK(J)-TGK(J-1))
         S1=0.
         IF (DL*DC.GT.0.) THEN
            S1=0.5D0*(DL+DC)
            SL3=3.D0*MIN(ABS(DL),ABS(DC))
            IF (ABS(S1).GT.SL3) S1=SIGN(SL3,S1)
         END IF
      END IF
      S2=DC
      IF (IOK(4).EQ.1) THEN
         DR=(VR(4)-VR(3))/(TGK(J+2)-TGK(J+1))
         S2=0.
         IF (DC*DR.GT.0.) THEN
            S2=0.5D0*(DC+DR)
            SL3=3.D0*MIN(ABS(DC),ABS(DR))
            IF (ABS(S2).GT.SL3) S2=SIGN(SL3,S2)
         END IF
      END IF
      CALL HERM1(H,VR(2),VR(3),S1,S2,TL-TGK(J),CKL,DUM)
      RETURN
      END
