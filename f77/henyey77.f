C
C     ------------------------------------------------------------------
C     SUBROUTINE ENUC - THERMONUCLEAR ENERGY GENERATION FROM THE
C     FULL NETWORK OF BFGH (1965) APPENDIX C - THE PP CHAIN WITH
C     HE3 EXPLICIT AND THE CNO BI-CYCLE WITH C12, C13, N14, AND
C     O16 EXPLICIT.  DERIVATIVES FOR THE JACOBIAN ARE CENTERED
C     DIFFERENCES OF THE EVALUATOR ENUCV, IN THE MANNER OF STATE
C     AND OPAC.
C     ------------------------------------------------------------------
      SUBROUTINE ENUC(TT,QQ,X,X3,XC2,XC3,XN4,XO6,Z,EPX,DEPTX,DEPQX)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      DEL=0.02
      CALL ENUCV(TT,QQ,X,X3,XC2,XC3,XN4,XO6,Z,E0)
      CALL ENUCV(TT*(1.+DEL),QQ,X,X3,XC2,XC3,XN4,XO6,Z,E1)
      CALL ENUCV(TT*(1.-DEL),QQ,X,X3,XC2,XC3,XN4,XO6,Z,E2)
      CALL ENUCV(TT,QQ*(1.+DEL),X,X3,XC2,XC3,XN4,XO6,Z,E3)
      CALL ENUCV(TT,QQ*(1.-DEL),X,X3,XC2,XC3,XN4,XO6,Z,E4)
      EPX=E0
      DEPTX=(E1-E2)/(2.*DEL*TT)
      DEPQX=(E3-E4)/(2.*DEL*QQ)
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE ENUCV - ONE EVALUATION OF THE NUCLEAR ENERGY
C     GENERATION RATE.  CHANNELS AND EFFECTIVE Q-VALUES (NEUTRINO
C     LOSSES REMOVED, BAHCALL 1989 CH. 3) -
C        P(P,E+ NU)D(P,G)HE3               Q =  6.671 MEV
C        HE3(HE3,2P)HE4                    Q = 12.860 MEV
C        HE3(HE4,G)BE7, PPII COMPLETION    Q = 18.982 MEV
C                       PPIII COMPLETION   Q = 12.50  MEV
C           (WEIGHTED BY THE BE7 BRANCHING FRACTION FB, WHICH
C           AFFECTS ONLY THE ENERGY - THE NEUTRINO LOSSES DIFFER
C           ON THE TWO CHANNELS.  BFGH 1965, APPENDIX C.)
C        C12(P,G)N13(B+ NU)C13             Q =  3.458 MEV
C        C13(P,G)N14                       Q =  7.551 MEV
C        N14(P,G)O15(B+ NU)N15(P,A)C12     Q = 14.02  MEV
C           (THE F15 FRACTION PROCEEDS N15(P,G)O16, Q = 21.18)
C        O16(P,G)F17(B+ NU)O17(P,A)N14     Q =  3.61  MEV
C     ------------------------------------------------------------------
      SUBROUTINE ENUCV(TT,QQ,X,X3,XC2,XC3,XN4,XO6,Z,EPS)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      F15=1.1D-3
      CMEV=1.602D-6
      CALL RATES(TT,QQ,X,X3,Z,C11,C33,C34,RC12,RC13,RC14,RC16,FB)
      E1=6.671*CMEV*C11*X*X
      E3=12.860*CMEV*C33*X3*X3
      E4=(18.982*(1.-FB)+12.50*FB)*CMEV*C34*X3
      EC2=3.458*CMEV*RC12*X*XC2
      EC3=7.551*CMEV*RC13*X*XC3
      EC4=(14.02*(1.-F15)+21.18*F15)*CMEV*RC14*X*XN4
      EC6=3.61*CMEV*RC16*X*XO6
      EPS=E1+E3+E4+EC2+EC3+EC4+EC6
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE RATES - REACTION RATE COEFFICIENTS OF THE FULL
C     NETWORK OF BFGH (1965) APPENDIX C, PER GRAM PER SECOND -
C        R(PP)  = C11*X1**2     P(P,E+ NU)D(P,G)HE3
C        R(33)  = C33*X3**2     HE3(HE3,2P)HE4
C        R(34)  = C34*X3        HE3(HE4,G)BE7 (X4 FOLDED IN)
C        R(112) = RC12*X1*X12   C12(P,G)N13(B+)C13
C        R(113) = RC13*X1*X13   C13(P,G)N14
C        R(114) = RC14*X1*X14   N14(P,G)O15(B+)N15(P,A OR P,G)
C        R(116) = RC16*X1*X16   O16(P,G)F17(B+)O17(P,A)N14
C     ALSO RETURNED IS FB, THE FRACTION OF BE7 COMPLETIONS THAT
C     PROCEED BY PROTON CAPTURE (THE PPIII BRANCH), USED ONLY FOR
C     THE ENERGY WEIGHTING AS IN BFGH APPENDIX C.  CROSS-SECTION
C     FACTORS FROM CAUGHLAN + FOWLER (1988), THE WORKING
C     EQUIVALENT OF THE BAHCALL (1989) PRESCRIPTIONS USED BY
C     LBA97, INCLUDING THE BE7 ELECTRON-CAPTURE RATE.  ELECTRON
C     SCREENING AFTER GRABOSKE, DEWITT, GROSSMAN + COOPER (1973) -
C     EXACT DEBYE-HUECKEL WEAK SCREENING, AND THE INTERMEDIATE
C     FORM H12 = F(XI12)*LAMBDA12**0.860 WITH
C        F(XI) = 0.380*((1+XI)**1.86 - XI**1.86 - 1)/XI**0.86,
C        XI12  = Z1*Z2/<Z**2>,
C     THE SMALLER OF THE TWO EXPONENTS BEING TAKEN (GDGC EQS. 14,
C     16, 19; REPRODUCES THEIR TABLE 3 CHARGE FACTORS TO BETTER
C     THAN ONE PER CENT).  STRONG SCREENING (LAMBDA12 ABOVE ABOUT
C     2) IS NOT YET INSTALLED.
C     ------------------------------------------------------------------
      SUBROUTINE RATES(TT,QQ,X1,X3,Z,C11,C33,C34,RC12,RC13,RC14,
     1   RC16,FB)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      RHO=QQ**3
      X4=MAX(1.-X1-X3-Z,0.D0)
      T9=1.D-9*TT
      T913=EXP(0.3333333333D0*LOG(T9))
      T923=T913*T913
      AVO=6.0221D23
C     SCREENING AFTER GRABOSKE, DEWITT, GROSSMAN + COOPER (1973).
C     THE WEAK (DEBYE-HUECKEL) EXPONENT FOR A UNIT-CHARGE PAIR IS
C        HW1 = 1.88E8 * SQRT(RHO*ZETA) / T**1.5,
C        ZETA = SUM OF X(I)*Z(I)*(Z(I)+1)/A(I),
C     AND THE PAIR PARAMETER OF GDGC IS LAMBDA12 = Z1*Z2*HW1.
C     FOR INTERMEDIATE SCREENING (THEIR EQS. 14, 16, AND 19 WITH
C     B = 0.860, KB = 0.380) THE EXPONENT IS
C        HI = F(XI12) * LAMBDA12**0.860,
C        F(XI) = 0.380*((1+XI)**1.86 - XI**1.86 - 1)/XI**0.86,
C        XI12  = Z1*Z2/<Z**2>,
C     WHICH REPRODUCES THEIR TABLE 3 CHARGE FACTORS TO BETTER
C     THAN ONE PER CENT FOR ALL TABULATED CASES.  THE SMALLER OF
C     THE WEAK AND INTERMEDIATE EXPONENTS IS TAKEN (THE PAPER
C     PUTS THE TRANSITION AT LAMBDA12 = 0.1 AND NOTES THE
C     DISCONTINUITY IS NEGLIGIBLE).  STRONG SCREENING (THEIR
C     LAMBDA12 ABOVE ABOUT 2) IS NOT YET INSTALLED.
      ZETA=1.984*X1+1.989*X3+1.499*X4+4.0*Z
      ANI=X1/1.008+X3/3.016+X4/4.003+Z/14.
      ZI2=(X1/1.008+4.*(X3/3.016+X4/4.003)+49.*Z/14.)/ANI
      HW1=1.88D8*SQRT(RHO*ZETA)/(TT*SQRT(TT))
C     SCREENING FACTORS FOR PAIR CHARGES Z1*Z2 = 1 (P+P),
C     4 (HE3+HE3, HE3+HE4, BE7+P), 6 (P+C), 7 (P+N14), 8 (P+O16)
      HP=HW1
      XI=1./ZI2
      FP=0.380*((1.+XI)**1.86-XI**1.86-1.)/XI**0.86
      HPI=FP*HW1**0.86
      IF (HPI.LT.HP) HP=HPI
      H3=4.*HW1
      XI=4./ZI2
      FP=0.380*((1.+XI)**1.86-XI**1.86-1.)/XI**0.86
      H3I=FP*(4.*HW1)**0.86
      IF (H3I.LT.H3) H3=H3I
      H6=6.*HW1
      XI=6./ZI2
      FP=0.380*((1.+XI)**1.86-XI**1.86-1.)/XI**0.86
      H6I=FP*(6.*HW1)**0.86
      IF (H6I.LT.H6) H6=H6I
      HC=7.*HW1
      XI=7./ZI2
      FP=0.380*((1.+XI)**1.86-XI**1.86-1.)/XI**0.86
      HCI=FP*(7.*HW1)**0.86
      IF (HCI.LT.HC) HC=HCI
      H8=8.*HW1
      XI=8./ZI2
      FP=0.380*((1.+XI)**1.86-XI**1.86-1.)/XI**0.86
      H8I=FP*(8.*HW1)**0.86
      IF (H8I.LT.H8) H8=H8I
      IF (HP.GT.6.) HP=6.
      IF (H3.GT.6.) H3=6.
      IF (H6.GT.6.) H6=6.
      IF (HC.GT.6.) HC=6.
      IF (H8.GT.6.) H8=6.
      FSP=EXP(HP)
      FS3=EXP(H3)
      FS6=EXP(H6)
      FSC=EXP(HC)
      FS8=EXP(H8)
C     P(P,E+ NU)D - CAUGHLAN + FOWLER (1988)
      SPP=0.
      ARG=-3.380/T913
      IF (ARG.GT.-600.) THEN
         POL=1.+0.123*T913+1.09*T923+0.938*T9
         SPP=4.01D-15/T923*EXP(ARG)*POL
      END IF
      C11=RHO*AVO*SPP/2.032*FSP
C     HE3(HE3,2P)HE4
      S33=0.
      ARG=-12.276/T913
      IF (ARG.GT.-600.) THEN
         POL=1.+0.034*T913-0.522*T923-0.124*T9+0.353*T9*T913
     1      +0.213*T9*T923
         S33=6.04D10/T923*EXP(ARG)*POL
      END IF
      C33=RHO*AVO*S33/18.19*FS3
C     HE3(HE4,G)BE7
      S34=0.
      W=1./(1.+0.0495*T9)
      T9A=T9*W
      ARG=-12.826/EXP(0.3333333333D0*LOG(T9A))
      IF (ARG.GT.-600.) THEN
         T9A56=EXP(0.8333333333D0*LOG(T9A))
         S34=5.61D6*T9A56/(T9*SQRT(T9))*EXP(ARG)
      END IF
      C34=RHO*X4*AVO*S34/12.07*FS3
C     C12(P,G)N13
      S12=0.
      ARG=-13.690/T913-(T9/1.500)**2
      IF (ARG.GT.-600.) THEN
         POL=1.+0.030*T913+1.19*T923+0.254*T9+2.06*T9*T913
     1      +1.12*T9*T923
         S12=2.04D7/T923*EXP(ARG)*POL
      END IF
      ARG=-4.925/T9
      IF (ARG.GT.-600.) S12=S12+1.08D5/(T9*SQRT(T9))*EXP(ARG)
      ARG=-18.179/T9
      IF (ARG.GT.-600.) S12=S12+2.15D5/(T9*SQRT(T9))*EXP(ARG)
      RC12=RHO*AVO*S12/12.096*FS6
C     C13(P,G)N14
      S13=0.
      ARG=-13.717/T913-(T9/2.000)**2
      IF (ARG.GT.-600.) THEN
         POL=1.+0.030*T913+0.958*T923+0.204*T9+1.39*T9*T913
     1      +0.753*T9*T923
         S13=8.01D7/T923*EXP(ARG)*POL
      END IF
      ARG=-5.701/T9
      IF (ARG.GT.-600.) S13=S13+1.21D6*EXP(ARG)
     1   /EXP(1.2D0*LOG(T9))
      RC13=RHO*AVO*S13/13.107*FS6
C     N14(P,G)O15 - THE CNO BOTTLENECK
      S2=0.
      S3=0.
      SR=0.
      ARG=-15.228/T913-0.092*T9*T9
      IF (ARG.GT.-600.) THEN
         POL=1.+0.027*T913-0.778*T923-0.149*T9+0.261*T9*T913
     1      +0.127*T9*T923
         SR=4.90D7/T923*EXP(ARG)*POL
      END IF
      ARG=-3.011/T9
      IF (ARG.GT.-600.) S2=2.37D3/(T9*SQRT(T9))*EXP(ARG)
      ARG=-12.53/T9
      IF (ARG.GT.-600.) S3=2.19D4*EXP(ARG)
      S14=SR+S2+S3
      RC14=RHO*AVO*S14/14.115*FSC
C     O16(P,G)F17
      S16=0.
      ARG=-16.692/T913
      IF (ARG.GT.-600.) S16=1.50D8/(T923*(1.+2.13*(1.
     1   -EXP(-0.728*T923))))*EXP(ARG)
      RC16=RHO*AVO*S16/16.123*FS8
C     BE7 BRANCHING - PROTON CAPTURE (PPIII) AGAINST ELECTRON
C     CAPTURE (PPII), BOTH CF88, FOR THE ENERGY WEIGHTING ONLY
      S17=0.
      ARG=-10.262/T913
      IF (ARG.GT.-600.) S17=3.11D5/T923*EXP(ARG)
      ARG=-7.306/T9
      IF (ARG.GT.-600.) S17=S17+2.53D3/(T9*SQRT(T9))*EXP(ARG)
      RL7P=RHO*X1*S17/1.008*FS3
      ARG=2.515D-3/T9
      IF (ARG.GT.80.) ARG=80.
      S7E=1.34D-10/SQRT(T9)*(1.-0.537*T913+3.86*T923
     1   +0.0027/T9*EXP(ARG))
      RL7E=RHO*0.5*(1.+X1)*S7E
      FB=0.
      IF (RL7P.GT.0.) FB=RL7P/(RL7P+RL7E)
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE BURN - ADVANCE THE COMPOSITION THROUGH THE TIME
C     STEP DT USING THE CONVERGED STRUCTURE, BY THE IMPLICIT
C     SCHEME OF BFGH (1965) APPENDIX C, EQ. (C9) - BACKWARD
C     DIFFERENCES WITH THE RATES AT THE ADVANCED EPOCH, STABLE
C     FOR TIME STEPS LARGE OR SMALL AGAINST ANY SPECIES LIFETIME.
C     THE THREE-STEP CYCLE OF THE APPENDIX IS ITERATED AT EACH
C     POINT - (1) THE FOUR CNO EQUATIONS (C17)-(C20), LINEAR IN
C     X12, X13, X14, X16 AT GIVEN X1, ARE SOLVED IN CLOSED FORM;
C     (2) THE HE3 EQUATION (C21) REDUCES TO A QUADRATIC; (3) THE
C     H1 EQUATION (C22) REDUCES TO A QUADRATIC, AND HE4 FOLLOWS
C     FROM THE SUM RULE (C23).  THE CYCLE REPEATS UNTIL X1 IS
C     UNCHANGED.  (THE HE3 MEASURE FOR TIME STEP CONTROL IS TAKEN
C     IN THE MAIN PROGRAM, AFTER MIXING.)
C     ------------------------------------------------------------------
      SUBROUTINE BURN(DT)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /GRID/ XI(201),EMPT(201),EMH(201),EMPH(201),N
      COMMON /VARBL/ R(201),F(201),T(201),Q(201),XH(201),X3A(201)
      COMMON /CNOC/ X12A(201),X13A(201),X14A(201),X16A(201)
      COMMON /STARP/ XM,XMI,ZMET,QHYD
      F15=1.1D-3
      AVO=6.0221D23
      CM1=1.008/AVO
      CM3=3.016/AVO
      CM12=12.000/AVO
      CM13=13.003/AVO
      CM14=14.003/AVO
      CM16=15.995/AVO
      DO 10 J=1,N
      X1N=XH(J)
      X3N=X3A(J)
      X12N=X12A(J)
      X13N=X13A(J)
      X14N=X14A(J)
      X16N=X16A(J)
      CALL RATES(T(J),Q(J),X1N,X3N,ZMET,C11,C33,C34,RC12,RC13,
     1   RC14,RC16,FB)
      X1=X1N
      X3=X3N
      XC2=X12N
      XC3=X13N
      XN4=X14N
      XO6=X16N
      DO 8 IT=1,12
C     STEP 1 - THE LINEAR CNO SOLVE OF EQS. (C17)-(C20) AT THE
C     CURRENT X1.  THE CYCLE C12-C13-N14 CLOSES THROUGH THE
C     (1-F15) RETURN TO C12 AND THE F15 LEAK THROUGH O16, SO THE
C     FOUR EQUATIONS REDUCE BY SUBSTITUTION TO ONE FOR N14.
      A12=DT*CM12*RC12*X1
      B12=DT*CM12*(1.-F15)*RC14*X1
      A13C=DT*CM13*RC12*X1
      A13=DT*CM13*RC13*X1
      A14C=DT*CM14*RC13*X1
      A14=DT*CM14*RC14*X1
      B14=DT*CM14*RC16*X1
      A16C=DT*CM16*F15*RC14*X1
      A16=DT*CM16*RC16*X1
      D16=1.+A16
      D13=1.+A13
      D12=1.+A12
      DD=1.+A14-B14*A16C/D16
      CC=A14C*A13C/D13
      RHS=X14N+B14*X16N/D16+A14C*X13N/D13
      DEN=DD-CC*B12/D12
      IF (DEN.LT.1.D-30) DEN=1.D-30
      XN4=(RHS+CC*X12N/D12)/DEN
      IF (XN4.LT.0.) XN4=0.
      XC2=(X12N+B12*XN4)/D12
      XC3=(X13N+A13C*XC2)/D13
      XO6=(X16N+A16C*XN4)/D16
C     STEP 2 - THE HE3 QUADRATIC OF EQ. (C21), IN THE
C     CANCELLATION-FREE ROOT FORM 2C/(B + SQRT(B**2 - 4AC)),
C     WHICH REMAINS EXACT AS THE QUADRATIC COEFFICIENT VANISHES
C     AT COOL POINTS
      RP=C11*X1*X1
      AQ=DT*CM3*2.*C33
      BQ=1.+DT*CM3*C34
      CQ=-(X3N+DT*CM3*RP)
      X3=2.*(-CQ)/(BQ+SQRT(BQ*BQ-4.*AQ*CQ))
      IF (X3.LT.0.) X3=0.
C     STEP 3 - THE H1 QUADRATIC OF EQ. (C22).  THREE PROTONS GO
C     PER PP REACTION, TWO RETURN PER HE3+HE3, ONE GOES PER BE7
C     COMPLETION, ONE PER C12 AND PER C13 CAPTURE, TWO PER N14
C     AND PER O16 CAPTURE.
      A1Q=DT*CM1*3.*C11
      B1Q=1.+DT*CM1*(RC12*XC2+RC13*XC3+2.*RC14*XN4+2.*RC16*XO6)
      C1Q=-(X1N+DT*CM1*(2.*C33*X3*X3-C34*X3))
      DISC=B1Q*B1Q-4.*A1Q*C1Q
      IF (DISC.LT.0.) DISC=0.
      X1NEW=2.*(-C1Q)/(B1Q+SQRT(DISC))
      IF (X1NEW.LT.0.) X1NEW=0.
      DX1=ABS(X1NEW-X1)
      X1=X1NEW
      IF (DX1.LT.1.D-12+1.D-8*X1) GO TO 9
    8 CONTINUE
    9 CONTINUE
      IF (X1+X3.GT.1.-ZMET) X3=MAX(1.-ZMET-X1,0.D0)
      XH(J)=X1
      X3A(J)=X3
      X12A(J)=XC2
      X13A(J)=XC3
      X14A(J)=XN4
      X16A(J)=XO6
   10 CONTINUE
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE REMOVE - THE OTHER HALF OF THE "TEMPORARY
C     POINTS" OF HFG (1964): POINTS ARE TEMPORARY, SO WHEN THE
C     FEATURE THAT DEMANDED THEM HAS MOVED ON, THEY GO.  A POINT
C     IS DROPPED WHEN THE ZONE FORMED BY JOINING ITS NEIGHBORS
C     WOULD STILL BE SMOOTH BY HALF THE SPLITTING TOLERANCE OF
C     REFINE (THE FACTOR OF TWO IS THE HYSTERESIS THAT PREVENTS
C     A SPLIT-AND-MERGE CYCLE).  WITHOUT REMOVAL THE ISOTHERMAL
C     CORE OF AN OLD GIANT HOARDS THE WHOLE MESH BUDGET - A
C     HUNDRED AND FIFTY POINTS RESOLVING NOTHING - WHILE THE
C     SHELL AND THE ENVELOPE STARVE AGAINST THE CAP.  AT MOST
C     FOUR POINTS GO PER STEP; THE CENTER PAIR AND THE SURFACE
C     PAIR ARE NEVER TOUCHED, AND NO POINT IS REMOVED AT A
C     CONVECTIVE BOUNDARY (WHERE THE FLAG CHANGES).
C     ------------------------------------------------------------------
      SUBROUTINE REMOVE(NREM)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /GRID/ XI(201),EMPT(201),EMH(201),EMPH(201),N
      COMMON /VARBL/ R(201),F(201),T(201),Q(201),XH(201),X3A(201)
      COMMON /CNOC/ X12A(201),X13A(201),X14A(201),X16A(201)
      COMMON /OLDT/ QN(201),EN(201),DTINV
      COMMON /FLAGS/ ICV(201)
      COMMON /STARP/ XM,XMI,ZMET,QHYD
      NREM=0
C     REMOVAL SERVES ONLY TO FREE BUDGET WHEN THE MESH PRESSES
C     AGAINST ITS CAP - A MAIN-SEQUENCE STAR WITH ROOM TO SPARE
C     KEEPS EVERY POINT, AND THE CALIBRATED TRACKS KEEP THEIR
C     DISCRETIZATION.
      IF (N.LT.190) RETURN
    5 IF (N.LE.60) GO TO 90
C     THE SMOOTHEST REMOVABLE POINT.  THE MEASURE CARRIES THE
C     DENSITY AS WELL AS THE TEMPERATURE AND COMPOSITION - AN
C     ISOTHERMAL CORE IS FLAT IN T AND X AT ANY ZONING, AND
C     WITHOUT THE DENSITY TERM AND THE WIDTH GUARD THE REMOVER
C     WOULD EAT THE CORE MESH UNTIL THE HYDROSTATIC DIFFERENCES
C     THEMSELVES GO BAD.
      WJ=1.D30
      JW=0
      DO 10 J=3,N-2
      IF (ICV(J-1).NE.ICV(J) .OR. ICV(J).NE.ICV(J+1)) GO TO 10
      IF (XI(J+1)-XI(J-1).GT.0.015D0) GO TO 10
      DLT=ABS(LOG(T(J+1)/T(J-1)))
      DXJ=ABS(XH(J+1)-XH(J-1))
      DLQ=ABS(LOG(Q(J+1)/Q(J-1)))
      W=DLT/0.10D0+DXJ/0.06D0+DLQ/0.50D0
      IF (W.LT.WJ) THEN
         WJ=W
         JW=J
      END IF
   10 CONTINUE
      IF (JW.EQ.0 .OR. WJ.GT.0.5D0) GO TO 90
C     SHIFT THE ARRAYS DOWN OVER THE DEPARTED POINT
      DO 30 JJ=JW,N-1
      XI(JJ)=XI(JJ+1)
      EMPT(JJ)=EMPT(JJ+1)
      R(JJ)=R(JJ+1)
      F(JJ)=F(JJ+1)
      T(JJ)=T(JJ+1)
      Q(JJ)=Q(JJ+1)
      XH(JJ)=XH(JJ+1)
      X3A(JJ)=X3A(JJ+1)
      X12A(JJ)=X12A(JJ+1)
      X13A(JJ)=X13A(JJ+1)
      X14A(JJ)=X14A(JJ+1)
      X16A(JJ)=X16A(JJ+1)
      QN(JJ)=QN(JJ+1)
      EN(JJ)=EN(JJ+1)
      ICV(JJ)=ICV(JJ+1)
   30 CONTINUE
      N=N-1
      NREM=NREM+1
      IF (NREM.LT.4) GO TO 5
   90 IF (NREM.EQ.0) RETURN
C     REGENERATE THE HALF-POINT MASS FUNCTIONS FROM THE ANALYTIC
C     LAW ON THE SHORTENED MESH
      NM1=N-1
      DO 95 J=1,NM1
      XX=0.5D0*(XI(J)+XI(J+1))
      EMH(J)=XMI*XX**3*(10.D0-15.D0*XX+6.D0*XX*XX)
      EMPH(J)=30.D0*XMI*XX*XX*(1.D0-XX)**2
   95 CONTINUE
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE REFINE - THE "TEMPORARY POINTS" OF HFG (1964).
C     BETWEEN TIME STEPS, ZONES WHOSE TEMPERATURE OR COMPOSITION
C     JUMP HAS GROWN TOO LARGE (THE MIGRATING SHELL SOURCE OF A
C     SPENT DWARF, THE EDGE OF A RETREATING CONVECTIVE CORE) ARE
C     SPLIT AT THEIR MASS MIDPOINT.  THE MESH COORDINATE XI OF
C     THE NEW POINT IS FOUND BY BISECTION ON THE ANALYTIC MASS
C     LAW, SO EVERY MASS FUNCTION REMAINS EXACT; THE VARIABLES,
C     THE COMPOSITION, AND THE OLD-EPOCH QUANTITIES ARE
C     INTERPOLATED, AND THE NEWTON PROCESS POLISHES THE REST.  AT
C     MOST FOUR POINTS ARE ADDED PER STEP, AND THE MESH IS CAPPED
C     AT 199 OF THE DIMENSIONED 201.
C     ------------------------------------------------------------------
      SUBROUTINE REFINE(NADD)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /GRID/ XI(201),EMPT(201),EMH(201),EMPH(201),N
      COMMON /VARBL/ R(201),F(201),T(201),Q(201),XH(201),X3A(201)
      COMMON /CNOC/ X12A(201),X13A(201),X14A(201),X16A(201)
      COMMON /OLDT/ QN(201),EN(201),DTINV
      COMMON /FLAGS/ ICV(201)
      COMMON /STARP/ XM,XMI,ZMET,QHYD
      NADD=0
    5 IF (N.GE.199) GO TO 90
      WJ=0.
      JW=0
      DO 10 J=1,N-1
      DLT=ABS(LOG(T(J+1)/T(J)))
      DXJ=ABS(XH(J+1)-XH(J))
      W=DLT/0.10D0+DXJ/0.06D0
      IF (W.GT.WJ) THEN
         WJ=W
         JW=J
      END IF
   10 CONTINUE
      IF (WJ.LE.1.D0) GO TO 90
C     BISECT THE ANALYTIC MASS LAW FOR THE MIDPOINT COORDINATE
      XMID=0.5D0*(EMPT(JW)+EMPT(JW+1))
      XA=XI(JW)
      XB=XI(JW+1)
      DO 20 IB=1,40
      XC=0.5D0*(XA+XB)
      EMC=XMI*XC**3*(10.D0-15.D0*XC+6.D0*XC*XC)
      IF (EMC.LT.XMID) XA=XC
      IF (EMC.GE.XMID) XB=XC
   20 CONTINUE
      XC=0.5D0*(XA+XB)
C     SHIFT THE ARRAYS UP AND INTERPOLATE THE NEW POINT
      FR=(XMID-EMPT(JW))/(EMPT(JW+1)-EMPT(JW))
      DO 30 JJ=N,JW+1,-1
      XI(JJ+1)=XI(JJ)
      EMPT(JJ+1)=EMPT(JJ)
      R(JJ+1)=R(JJ)
      F(JJ+1)=F(JJ)
      T(JJ+1)=T(JJ)
      Q(JJ+1)=Q(JJ)
      XH(JJ+1)=XH(JJ)
      X3A(JJ+1)=X3A(JJ)
      X12A(JJ+1)=X12A(JJ)
      X13A(JJ+1)=X13A(JJ)
      X14A(JJ+1)=X14A(JJ)
      X16A(JJ+1)=X16A(JJ)
      QN(JJ+1)=QN(JJ)
      EN(JJ+1)=EN(JJ)
      ICV(JJ+1)=ICV(JJ)
   30 CONTINUE
      J=JW
      XI(J+1)=XC
      EMPT(J+1)=XMID
      T(J+1)=EXP((1.D0-FR)*LOG(T(J))+FR*LOG(T(J+2)))
      Q(J+1)=EXP((1.D0-FR)*LOG(Q(J))+FR*LOG(Q(J+2)))
      QN(J+1)=EXP((1.D0-FR)*LOG(MAX(QN(J),1.D-30))
     1   +FR*LOG(MAX(QN(J+2),1.D-30)))
      EN(J+1)=(1.D0-FR)*EN(J)+FR*EN(J+2)
      R(J+1)=((1.D0-FR)*R(J)**3+FR*R(J+2)**3)**(1.D0/3.D0)
      XL=(1.D0-FR)*XI(J)**2*F(J)+FR*XI(J+2)**2*F(J+2)
      F(J+1)=XL/(XC*XC)
      XH(J+1)=(1.D0-FR)*XH(J)+FR*XH(J+2)
      X3A(J+1)=(1.D0-FR)*X3A(J)+FR*X3A(J+2)
      X12A(J+1)=(1.D0-FR)*X12A(J)+FR*X12A(J+2)
      X13A(J+1)=(1.D0-FR)*X13A(J)+FR*X13A(J+2)
      X14A(J+1)=(1.D0-FR)*X14A(J)+FR*X14A(J+2)
      X16A(J+1)=(1.D0-FR)*X16A(J)+FR*X16A(J+2)
      ICV(J+1)=ICV(J)
      N=N+1
      NADD=NADD+1
      IF (NADD.LT.4) GO TO 5
C     REGENERATE THE HALF-POINT MASS FUNCTIONS FROM THE ANALYTIC
C     LAW ON THE NEW MESH
   90 IF (NADD.EQ.0) RETURN
      NM1=N-1
      DO 95 J=1,NM1
      XX=0.5D0*(XI(J)+XI(J+1))
      EMH(J)=XMI*XX**3*(10.D0-15.D0*XX+6.D0*XX*XX)
      EMPH(J)=30.D0*XMI*XX*XX*(1.D0-XX)**2
   95 CONTINUE
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE MIX - INSTANTANEOUS MIXING OF THE HYDROGEN
C     ABUNDANCE OVER EACH CONTIGUOUS CONVECTIVE REGION (MASS
C     WEIGHTED MEAN OVER THE POINTS OF THE REGION).
C     ------------------------------------------------------------------
      SUBROUTINE MIX
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /GRID/ XI(201),EMPT(201),EMH(201),EMPH(201),N
      COMMON /VARBL/ R(201),F(201),T(201),Q(201),XH(201),X3A(201)
      COMMON /CNOC/ X12A(201),X13A(201),X14A(201),X16A(201)
      COMMON /FLAGS/ ICV(201)
      COMMON /STARP/ XM,XMI,ZMET,QHYD
      NM1=N-1
      J=1
   10 IF (ICV(J).EQ.0) GO TO 40
      K1=J
   20 IF (J.EQ.NM1) GO TO 25
      IF (ICV(J+1).EQ.0) GO TO 25
      J=J+1
      GO TO 20
   25 K2=J+1
      SW=0.
      SX=0.
      SX3=0.
      S12=0.
      S13=0.
      S14=0.
      S16=0.
      DO 30 JP=K1,K2
      W=0.
      IF (JP.EQ.1) W=EMH(1)
      IF (JP.GT.1 .AND. JP.LT.N) W=EMH(JP)-EMH(JP-1)
      IF (JP.EQ.N) W=XM-EMH(NM1)
      SW=SW+W
      SX=SX+W*XH(JP)
      SX3=SX3+W*X3A(JP)
      S12=S12+W*X12A(JP)
      S13=S13+W*X13A(JP)
      S14=S14+W*X14A(JP)
      S16=S16+W*X16A(JP)
   30 CONTINUE
      XB=SX/SW
      X3B=SX3/SW
      X12B=S12/SW
      X13B=S13/SW
      X14B=S14/SW
      X16B=S16/SW
      DO 35 JP=K1,K2
      XH(JP)=XB
      X3A(JP)=X3B
      X12A(JP)=X12B
      X13A(JP)=X13B
      X14A(JP)=X14B
   35 X16A(JP)=X16B
   40 J=J+1
      IF (J.LE.NM1) GO TO 10
      RETURN
      END
