C     ------------------------------------------------------------------
C     SUBROUTINE HLCV - THE ELECTRON-CONDUCTION OPACITY OF
C     HUBBARD + LAMPE (1969, AP. J. SUPPL. 18, 297), FROM THEIR
C     TABLES 1 (HYDROGEN) AND 2 (HELIUM), TRANSCRIBED ON THE
C     SUBGRID LOG RHO = 0.5(0.5)5.0, LOG T = 5.0(0.2)7.6 THAT
C     BRACKETS THE DEGENERATE CORES OF OLD DWARFS.  CELLS THE
C     AUTHORS EXCLUDED (THEIR THEORY-BREAKDOWN REGIONS) CARRY THE
C     SENTINEL 99 AND ARE BRIDGED AT RUN TIME.  INTERPOLATION IS
C     MONOTONE-LIMITED HERMITE OVER THE DEFINED CELLS OF EACH
C     ROW, THEN ACROSS ROWS; OUTSIDE THE GRID THE EDGE SLOPES
C     CONTINUE LINEARLY (CONDUCTION IS POWER-LAW SMOOTH IN THE
C     LOGS).  THE MIXTURE IS INTERPOLATED LINEARLY IN THE
C     HYDROGEN MASS FRACTION BETWEEN THE PURE TABLES, IN THE
C     LOGARITHM.  RETURNED IS KAPPA(COND) IN CM2/G.
C     ------------------------------------------------------------------
      SUBROUTINE HLCV(TL,RL,X,CKC)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      DIMENSION VH(4),VE(4),IOH(4),IOE(4)
      J=IDINT((TL-5.0D0)/0.2D0)+1
      IF (J.LT.1) J=1
      IF (J.GT.13) J=13
      DO 10 M=1,4
      JR=J+M-2
      IOH(M)=0
      IOE(M)=0
      VH(M)=0.
      VE(M)=0.
      IF (JR.LT.1 .OR. JR.GT.14) GO TO 10
      CALL HLROW(1,JR,RL,VH(M),IOH(M))
      CALL HLROW(2,JR,RL,VE(M),IOE(M))
   10 CONTINUE
      CALL HLTS(VH,IOH,TL,J,CH)
      CALL HLTS(VE,IOE,TL,J,CE)
      CKC=10.D0**(X*CH+(1.D0-X)*CE)
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE HLTS - THE ACROSS-ROWS (TEMPERATURE) STEP OF THE
C     HUBBARD-LAMPE INTERPOLATION - MONOTONE-LIMITED HERMITE ON
C     THE FOUR ROW VALUES WHERE DEFINED, DEGRADING GRACEFULLY AT
C     THE RAGGED EDGES.
C     ------------------------------------------------------------------
      SUBROUTINE HLTS(VR,IOK,TL,J,CV)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      DIMENSION VR(4),IOK(4)
      T2=5.0D0+0.2D0*(J-1)
      IF (IOK(2).EQ.1 .AND. IOK(3).EQ.1) GO TO 10
C     ONE OR BOTH BRACKETING ROWS UNDEFINED - USE WHAT EXISTS
      CV=0.
      IF (IOK(3).EQ.1) CV=VR(3)
      IF (IOK(2).EQ.1) CV=VR(2)
      RETURN
   10 DC=(VR(3)-VR(2))/0.2D0
      S1=DC
      IF (IOK(1).EQ.1) THEN
         DL=(VR(2)-VR(1))/0.2D0
         S1=0.
         IF (DL*DC.GT.0.) THEN
            S1=0.5D0*(DL+DC)
            SL3=3.D0*MIN(ABS(DL),ABS(DC))
            IF (ABS(S1).GT.SL3) S1=SIGN(SL3,S1)
         END IF
      END IF
      S2=DC
      IF (IOK(4).EQ.1) THEN
         DR=(VR(4)-VR(3))/0.2D0
         S2=0.
         IF (DC*DR.GT.0.) THEN
            S2=0.5D0*(DC+DR)
            SL3=3.D0*MIN(ABS(DC),ABS(DR))
            IF (ABS(S2).GT.SL3) S2=SIGN(SL3,S2)
         END IF
      END IF
      CALL HERM1(0.2D0,VR(2),VR(3),S1,S2,TL-T2,CV,DUM)
      RETURN
      END
C
C     ------------------------------------------------------------------
C     SUBROUTINE HLROW - ONE ROW OF A HUBBARD-LAMPE TABLE
C     EVALUATED AT LOG RHO.  THE DEFINED CELLS OF THE ROW ARE
C     GATHERED (THE EXCLUDED REGIONS LEAVE EDGE GAPS AND, FOR
C     HELIUM, INTERIOR GAPS), AND A MONOTONE-LIMITED HERMITE IS
C     TAKEN OVER THE GATHERED, GENERALLY NONUNIFORM ABSCISSAE.
C     ------------------------------------------------------------------
      SUBROUTINE HLROW(IS,JR,RL,V,IOK)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON /HLCT/ HLT(10,14,2)
      DIMENSION XD(10),YD(10)
      IOK=0
      ND=0
      DO 10 K=1,10
      IF (HLT(K,JR,IS).GT.50.) GO TO 10
      ND=ND+1
      XD(ND)=0.5D0*K
      YD(ND)=HLT(K,JR,IS)
   10 CONTINUE
      IF (ND.LT.2) RETURN
      IOK=1
      K=1
      DO 20 KK=2,ND-1
      IF (RL.GE.XD(KK)) K=KK
   20 CONTINUE
      H=XD(K+1)-XD(K)
      DC=(YD(K+1)-YD(K))/H
      S1=DC
      IF (K.GT.1) THEN
         DL=(YD(K)-YD(K-1))/(XD(K)-XD(K-1))
         S1=0.
         IF (DL*DC.GT.0.) THEN
            S1=0.5D0*(DL+DC)
            SL3=3.D0*MIN(ABS(DL),ABS(DC))
            IF (ABS(S1).GT.SL3) S1=SIGN(SL3,S1)
         END IF
      END IF
      S2=DC
      IF (K.LT.ND-1) THEN
         DR=(YD(K+2)-YD(K+1))/(XD(K+2)-XD(K+1))
         S2=0.
         IF (DC*DR.GT.0.) THEN
            S2=0.5D0*(DC+DR)
            SL3=3.D0*MIN(ABS(DC),ABS(DR))
            IF (ABS(S2).GT.SL3) S2=SIGN(SL3,S2)
         END IF
      END IF
      CALL HERM1(H,YD(K),YD(K+1),S1,S2,RL-XD(K),V,DUM)
      RETURN
      END
